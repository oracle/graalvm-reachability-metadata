package org_dom4j.dom4j;

import org.dom4j.Document;
import org.dom4j.DocumentHelper;
import org.dom4j.Element;
import org.dom4j.Namespace;
import org.dom4j.QName;
import org.dom4j.io.OutputFormat;
import org.dom4j.io.XMLWriter;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;

import java.io.StringWriter;

import static org.junit.jupiter.api.Assertions.assertEquals;

/// Exercises dom4j's XML writer subsystem to serialize a namespaced shipment report.
public class XmlShipmentReportWriterTest {
    @Test
    @Timeout(60)
    public void writesPrettyPrintedShipmentReport() throws Exception {
        Namespace report = Namespace.get("r", "urn:example:report");
        Element root = DocumentHelper.createElement(QName.get("shipmentReport", report));
        root.addAttribute("id", "SHP-2048");
        root.addComment("Generated by fulfillment service");

        Element shipment = root.addElement(QName.get("shipment", report));
        shipment.addAttribute("status", "ready");
        shipment.addElement(QName.get("destination", report)).addText("Lyon & Paris");
        shipment.addElement(QName.get("instructions", report))
                .addCDATA("Leave at dock <B> before 17:00");
        Document document = DocumentHelper.createDocument(root);

        OutputFormat format = OutputFormat.createPrettyPrint();
        format.setEncoding("UTF-8");
        StringWriter output = new StringWriter();
        XMLWriter writer = new XMLWriter(output, format);
        writer.write(document);
        writer.close();

        assertEquals("""
                <?xml version="1.0" encoding="UTF-8"?>

                <r:shipmentReport xmlns:r="urn:example:report" id="SHP-2048">
                  <!--Generated by fulfillment service-->
                  <r:shipment status="ready">
                    <r:destination>Lyon &amp; Paris</r:destination>
                    <r:instructions><![CDATA[Leave at dock <B> before 17:00]]></r:instructions>
                  </r:shipment>
                </r:shipmentReport>
                """, output.toString());
    }
}
