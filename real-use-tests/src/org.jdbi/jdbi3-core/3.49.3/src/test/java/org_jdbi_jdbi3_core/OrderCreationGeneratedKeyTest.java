package org_jdbi_jdbi3_core;

import org.jdbi.v3.core.Jdbi;
import org.junit.jupiter.api.Test;

import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/// Exercises Jdbi's generated-key result subsystem for creating order records.
public class OrderCreationGeneratedKeyTest {
    @Test
    void createsAnOrderAndReadsItsGeneratedIdentifier() {
        Jdbi jdbi = Jdbi.create("jdbc:h2:mem:generated_orders");

        jdbi.useHandle(handle -> {
            handle.execute("""
                    CREATE TABLE customer_order (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        order_number VARCHAR(32) NOT NULL,
                        status VARCHAR(32) NOT NULL
                    )
                    """);

            long generatedId = handle.createUpdate("""
                    INSERT INTO customer_order (order_number, status)
                    VALUES (:orderNumber, :status)
                    """)
                    .bind("orderNumber", "ORD-1042")
                    .bind("status", "PENDING")
                    .executeAndReturnGeneratedKeys("id")
                    .mapTo(Long.class)
                    .one();

            assertTrue(generatedId > 0);
            assertEquals(Map.of(
                    "id", generatedId,
                    "order_number", "ORD-1042",
                    "status", "PENDING"),
                    handle.createQuery("""
                            SELECT id, order_number, status
                            FROM customer_order
                            WHERE id = :id
                            """)
                            .bind("id", generatedId)
                            .mapToMap()
                            .one());
        });
    }
}
