package com_h2database.h2;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLIntegrityConstraintViolationException;
import java.sql.Savepoint;
import java.sql.Statement;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.h2.api.ErrorCode;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

/**
 * The embedded SQL engine reached through the H2 JDBC driver: DDL with constraints, prepared
 * batches, generated keys, transactions and savepoints, joins, aggregates, window functions,
 * `MERGE`, and constraint violations reported as H2 error codes.
 *
 * An order ledger keeps customers, products, and order lines in an in-memory database, places
 * orders atomically, rolls back a failed line with a savepoint, and produces revenue reports.
 */
public class OrderLedgerSqlEngineTest {

    private static final String SCHEMA = """
            CREATE TABLE customer (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email VARCHAR(120) NOT NULL UNIQUE,
                region VARCHAR(20) NOT NULL
            );
            CREATE TABLE product (
                sku VARCHAR(20) PRIMARY KEY,
                title VARCHAR(80) NOT NULL,
                price DECIMAL(10, 2) NOT NULL CHECK (price > 0),
                stock INT NOT NULL CHECK (stock >= 0)
            );
            CREATE TABLE purchase_order (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_id BIGINT NOT NULL REFERENCES customer(id),
                placed_on DATE NOT NULL
            );
            CREATE TABLE order_line (
                order_id BIGINT NOT NULL REFERENCES purchase_order(id) ON DELETE CASCADE,
                sku VARCHAR(20) NOT NULL REFERENCES product(sku),
                quantity INT NOT NULL CHECK (quantity > 0),
                PRIMARY KEY (order_id, sku)
            );
            """;

    private Connection connection;

    @BeforeEach
    void openLedger() throws SQLException {
        String url = "jdbc:h2:mem:ledger-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1";
        connection = DriverManager.getConnection(url, "sa", "");
        try (Statement statement = connection.createStatement()) {
            statement.execute(SCHEMA);
        }
        long alice = registerCustomer("alice@example.com", "EU");
        long bob = registerCustomer("bob@example.com", "US");
        registerCustomer("carol@example.com", "EU");
        stockProducts();
        placeOrder(alice, LocalDate.of(2024, 3, 1), Map.of("KB-01", 2, "MS-02", 1));
        placeOrder(bob, LocalDate.of(2024, 3, 2), Map.of("MN-27", 1));
        placeOrder(alice, LocalDate.of(2024, 3, 5), Map.of("MS-02", 3));
    }

    @AfterEach
    void closeLedger() throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute("SHUTDOWN");
        }
        connection.close();
    }

    @Test
    void assignsIdentityKeysAndDecrementsStockForPlacedOrders() throws SQLException {
        try (Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery("SELECT sku, stock FROM product ORDER BY sku")) {
            Map<String, Integer> stock = new LinkedHashMap<>();
            while (rows.next()) {
                stock.put(rows.getString("sku"), rows.getInt("stock"));
            }
            assertEquals(Map.of("KB-01", 8, "MN-27", 4, "MS-02", 16), stock);
        }
        assertEquals(List.of(1L, 2L, 3L), queryLongs("SELECT id FROM purchase_order ORDER BY id"));
        assertEquals(List.of(1L, 2L, 3L), queryLongs("SELECT id FROM customer ORDER BY id"));
    }

    @Test
    void reportsRevenuePerRegionWithJoinsAndAggregates() throws SQLException {
        String report = """
                SELECT c.region, COUNT(DISTINCT o.id) AS orders, SUM(l.quantity * p.price) AS revenue
                FROM customer c
                JOIN purchase_order o ON o.customer_id = c.id
                JOIN order_line l ON l.order_id = o.id
                JOIN product p ON p.sku = l.sku
                GROUP BY c.region
                ORDER BY revenue DESC
                """;
        try (Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery(report)) {
            assertTrue(rows.next());
            assertEquals("US", rows.getString("region"));
            assertEquals(1, rows.getInt("orders"));
            assertEquals(new BigDecimal("249.00"), rows.getBigDecimal("revenue"));
            assertTrue(rows.next());
            assertEquals("EU", rows.getString("region"));
            assertEquals(2, rows.getInt("orders"));
            assertEquals(new BigDecimal("219.94"), rows.getBigDecimal("revenue"));
            assertFalse(rows.next());
        }
    }

    @Test
    void ranksCustomerOrdersWithWindowFunctions() throws SQLException {
        String ranking = """
                SELECT c.email, o.placed_on,
                       ROW_NUMBER() OVER (PARTITION BY c.id ORDER BY o.placed_on) AS nth,
                       SUM(l.quantity) OVER (PARTITION BY c.id ORDER BY o.placed_on) AS running_items
                FROM customer c
                JOIN purchase_order o ON o.customer_id = c.id
                JOIN (SELECT order_id, SUM(quantity) AS quantity FROM order_line GROUP BY order_id) l
                  ON l.order_id = o.id
                ORDER BY c.email, nth
                """;
        List<String> lines = new ArrayList<>();
        try (Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery(ranking)) {
            while (rows.next()) {
                lines.add(rows.getString("email") + " " + rows.getObject("placed_on", LocalDate.class)
                        + " #" + rows.getInt("nth") + " items=" + rows.getLong("running_items"));
            }
        }
        assertEquals(List.of(
                "alice@example.com 2024-03-01 #1 items=3",
                "alice@example.com 2024-03-05 #2 items=6",
                "bob@example.com 2024-03-02 #1 items=1"), lines);
    }

    @Test
    void rollsBackOnlyTheFailedLineToASavepoint() throws SQLException {
        long carol = customerId("carol@example.com");
        connection.setAutoCommit(false);
        long orderId = insertOrder(carol, LocalDate.of(2024, 3, 9));
        addLine(orderId, "KB-01", 1);
        Savepoint beforeMonitors = connection.setSavepoint("before_monitors");
        SQLException outOfStock = assertThrows(SQLException.class, () -> addLine(orderId, "MN-27", 50));
        assertEquals(ErrorCode.CHECK_CONSTRAINT_VIOLATED_1, outOfStock.getErrorCode());
        connection.rollback(beforeMonitors);
        connection.commit();
        connection.setAutoCommit(true);

        assertEquals(List.of(1L), queryLongs("SELECT quantity FROM order_line WHERE order_id = " + orderId));
        assertEquals(List.of(7L, 4L), queryLongs("SELECT stock FROM product WHERE sku IN ('KB-01', 'MN-27') ORDER BY sku"));
    }

    @Test
    void discardsAWholeOrderWhenTheTransactionRollsBack() throws SQLException {
        long bob = customerId("bob@example.com");
        connection.setAutoCommit(false);
        long orderId = insertOrder(bob, LocalDate.of(2024, 3, 10));
        addLine(orderId, "MS-02", 2);
        connection.rollback();
        connection.setAutoCommit(true);

        assertEquals(List.of(3L), queryLongs("SELECT COUNT(*) FROM purchase_order"));
        assertEquals(List.of(16L), queryLongs("SELECT stock FROM product WHERE sku = 'MS-02'"));
    }

    @Test
    void reportsConstraintViolationsWithH2ErrorCodes() throws SQLException {
        SQLException duplicate = assertThrows(SQLIntegrityConstraintViolationException.class,
                () -> registerCustomer("alice@example.com", "APAC"));
        assertEquals(ErrorCode.DUPLICATE_KEY_1, duplicate.getErrorCode());

        SQLException orphan = assertThrows(SQLIntegrityConstraintViolationException.class,
                () -> insertOrder(999L, LocalDate.of(2024, 4, 1)));
        assertEquals(ErrorCode.REFERENTIAL_INTEGRITY_VIOLATED_PARENT_MISSING_1, orphan.getErrorCode());

        try (Statement statement = connection.createStatement()) {
            SQLException inUse = assertThrows(SQLException.class,
                    () -> statement.executeUpdate("DELETE FROM product WHERE sku = 'KB-01'"));
            assertEquals(ErrorCode.REFERENTIAL_INTEGRITY_VIOLATED_CHILD_EXISTS_1, inUse.getErrorCode());
            SQLException badSql = assertThrows(SQLException.class,
                    () -> statement.executeQuery("SELECT nope FROM product"));
            assertEquals(ErrorCode.COLUMN_NOT_FOUND_1, badSql.getErrorCode());
        }
    }

    @Test
    void upsertsPriceListWithMergeAndCascadesOrderDeletion() throws SQLException {
        String merge = """
                MERGE INTO product p
                USING (VALUES ('KB-01', 'Mechanical keyboard', 54.99), ('HS-09', 'Headset', 79.50)) AS s(sku, title, price)
                ON p.sku = s.sku
                WHEN MATCHED THEN UPDATE SET price = s.price
                WHEN NOT MATCHED THEN INSERT (sku, title, price, stock) VALUES (s.sku, s.title, s.price, 0)
                """;
        try (Statement statement = connection.createStatement()) {
            assertEquals(2, statement.executeUpdate(merge));
            try (ResultSet rows = statement.executeQuery(
                    "SELECT sku, price, stock FROM product WHERE sku IN ('KB-01', 'HS-09') ORDER BY sku")) {
                assertTrue(rows.next());
                assertEquals("HS-09", rows.getString(1));
                assertEquals(new BigDecimal("79.50"), rows.getBigDecimal(2));
                assertEquals(0, rows.getInt(3));
                assertTrue(rows.next());
                assertEquals("KB-01", rows.getString(1));
                assertEquals(new BigDecimal("54.99"), rows.getBigDecimal(2));
                assertEquals(8, rows.getInt(3));
            }
            assertEquals(1, statement.executeUpdate("DELETE FROM purchase_order WHERE id = 1"));
        }
        assertEquals(List.of(2L), queryLongs("SELECT COUNT(*) FROM order_line"));
    }

    private long registerCustomer(String email, String region) throws SQLException {
        try (PreparedStatement insert = connection.prepareStatement(
                "INSERT INTO customer(email, region) VALUES (?, ?)", Statement.RETURN_GENERATED_KEYS)) {
            insert.setString(1, email);
            insert.setString(2, region);
            insert.executeUpdate();
            return generatedKey(insert);
        }
    }

    private void stockProducts() throws SQLException {
        try (PreparedStatement insert = connection.prepareStatement(
                "INSERT INTO product(sku, title, price, stock) VALUES (?, ?, ?, ?)")) {
            addProduct(insert, "KB-01", "Mechanical keyboard", "59.99", 10);
            addProduct(insert, "MS-02", "Wireless mouse", "24.99", 20);
            addProduct(insert, "MN-27", "27 inch monitor", "249.00", 5);
            int[] counts = insert.executeBatch();
            assertEquals(3, counts.length);
        }
    }

    private static void addProduct(PreparedStatement insert, String sku, String title, String price, int stock)
            throws SQLException {
        insert.setString(1, sku);
        insert.setString(2, title);
        insert.setBigDecimal(3, new BigDecimal(price));
        insert.setInt(4, stock);
        insert.addBatch();
    }

    private void placeOrder(long customerId, LocalDate placedOn, Map<String, Integer> lines) throws SQLException {
        connection.setAutoCommit(false);
        try {
            long orderId = insertOrder(customerId, placedOn);
            for (Map.Entry<String, Integer> line : lines.entrySet()) {
                addLine(orderId, line.getKey(), line.getValue());
            }
            connection.commit();
        } catch (SQLException e) {
            connection.rollback();
            throw e;
        } finally {
            connection.setAutoCommit(true);
        }
    }

    private long insertOrder(long customerId, LocalDate placedOn) throws SQLException {
        try (PreparedStatement insert = connection.prepareStatement(
                "INSERT INTO purchase_order(customer_id, placed_on) VALUES (?, ?)", new String[] {"ID"})) {
            insert.setLong(1, customerId);
            insert.setObject(2, placedOn);
            insert.executeUpdate();
            return generatedKey(insert);
        }
    }

    private void addLine(long orderId, String sku, int quantity) throws SQLException {
        try (PreparedStatement reserve = connection.prepareStatement(
                "UPDATE product SET stock = stock - ? WHERE sku = ?");
                PreparedStatement insert = connection.prepareStatement(
                        "INSERT INTO order_line(order_id, sku, quantity) VALUES (?, ?, ?)")) {
            reserve.setInt(1, quantity);
            reserve.setString(2, sku);
            assertEquals(1, reserve.executeUpdate());
            insert.setLong(1, orderId);
            insert.setString(2, sku);
            insert.setInt(3, quantity);
            insert.executeUpdate();
        }
    }

    private long customerId(String email) throws SQLException {
        try (PreparedStatement query = connection.prepareStatement("SELECT id FROM customer WHERE email = ?")) {
            query.setString(1, email);
            try (ResultSet rows = query.executeQuery()) {
                assertTrue(rows.next());
                return rows.getLong(1);
            }
        }
    }

    private static long generatedKey(Statement statement) throws SQLException {
        try (ResultSet keys = statement.getGeneratedKeys()) {
            assertTrue(keys.next());
            return keys.getLong(1);
        }
    }

    private List<Long> queryLongs(String sql) throws SQLException {
        List<Long> values = new ArrayList<>();
        try (Statement statement = connection.createStatement();
                ResultSet rows = statement.executeQuery(sql)) {
            while (rows.next()) {
                values.add(rows.getLong(1));
            }
        }
        return values;
    }
}
