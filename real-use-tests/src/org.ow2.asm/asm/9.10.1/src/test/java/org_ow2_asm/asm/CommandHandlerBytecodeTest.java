package org_ow2_asm.asm;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassVisitor;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.FieldVisitor;
import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.Type;

import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Builds and inspects generated bytecode for an application command handler. */
public class CommandHandlerBytecodeTest {
    @Test
    @Timeout(60)
    void generatesACommandHandlerClassAndReadsItsPublicContract() {
        String handlerDescriptor = Type.getMethodDescriptor(
                Type.getType(String.class), Type.getType(String.class));
        ClassWriter writer = new ClassWriter(0);
        writer.visit(Opcodes.V17, Opcodes.ACC_PUBLIC | Opcodes.ACC_FINAL,
                "example/GeneratedCommandHandler", null, Type.getInternalName(Object.class), null);
        writer.visitField(Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC | Opcodes.ACC_FINAL,
                "COMMAND_NAME", Type.getDescriptor(String.class), null, "accept").visitEnd();

        MethodVisitor constructor = writer.visitMethod(Opcodes.ACC_PUBLIC, "<init>", "()V", null, null);
        constructor.visitCode();
        constructor.visitVarInsn(Opcodes.ALOAD, 0);
        constructor.visitMethodInsn(Opcodes.INVOKESPECIAL, Type.getInternalName(Object.class),
                "<init>", "()V", false);
        constructor.visitInsn(Opcodes.RETURN);
        constructor.visitMaxs(1, 1);
        constructor.visitEnd();

        MethodVisitor handler = writer.visitMethod(Opcodes.ACC_PUBLIC, "handle", handlerDescriptor, null, null);
        handler.visitCode();
        handler.visitLdcInsn("accepted");
        handler.visitInsn(Opcodes.ARETURN);
        handler.visitMaxs(1, 2);
        handler.visitEnd();
        writer.visitEnd();

        List<String> fields = new ArrayList<>();
        List<String> methods = new ArrayList<>();
        List<String> constants = new ArrayList<>();
        ClassReader reader = new ClassReader(writer.toByteArray());
        reader.accept(new ClassVisitor(Opcodes.ASM9) {
            @Override
            public FieldVisitor visitField(int access, String name, String descriptor,
                    String signature, Object value) {
                fields.add(name + descriptor + "=" + value);
                return null;
            }

            @Override
            public MethodVisitor visitMethod(int access, String name, String descriptor,
                    String signature, String[] exceptions) {
                methods.add(name + descriptor);
                return new MethodVisitor(Opcodes.ASM9) {
                    @Override
                    public void visitLdcInsn(Object value) {
                        constants.add(String.valueOf(value));
                    }
                };
            }
        }, ClassReader.SKIP_DEBUG);

        assertEquals("example/GeneratedCommandHandler", reader.getClassName());
        assertEquals(List.of("COMMAND_NAMELjava/lang/String;=accept"), fields);
        assertEquals(List.of("<init>()V", "handle(Ljava/lang/String;)Ljava/lang/String;"), methods);
        assertTrue(constants.contains("accepted"));
    }
}
