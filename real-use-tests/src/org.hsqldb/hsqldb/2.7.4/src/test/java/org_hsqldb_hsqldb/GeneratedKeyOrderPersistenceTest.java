package org_hsqldb_hsqldb;

import org.hsqldb.jdbc.JDBCDataSource;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/// Exercises HSQLDB's JDBC generated-key subsystem for persisting a new order.
public class GeneratedKeyOrderPersistenceTest {
    @Test
    @Timeout(60)
    public void insertsAnOrderAndUsesItsGeneratedId() throws Exception {
        JDBCDataSource dataSource = new JDBCDataSource();
        dataSource.setDatabase("mem:generated_key_order_scenario");
        dataSource.setUser("SA");
        dataSource.setPassword("");

        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement()) {
            statement.executeUpdate("CREATE TABLE orders ("
                    + "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "description VARCHAR(128))");
        }

        long generatedId;
        try (Connection connection = dataSource.getConnection();
                Statement insert = connection.createStatement()) {
            assertEquals(1, insert.executeUpdate(
                    "INSERT INTO orders (description) VALUES ('Replacement filters')",
                    Statement.RETURN_GENERATED_KEYS));
            try (ResultSet keys = insert.getGeneratedKeys()) {
                assertTrue(keys.next());
                generatedId = keys.getLong(1);
                assertTrue(!keys.next());
            }
        }

        try (Connection connection = dataSource.getConnection();
                PreparedStatement query = connection.prepareStatement(
                        "SELECT description FROM orders WHERE id = ?")) {
            query.setLong(1, generatedId);
            try (ResultSet resultSet = query.executeQuery()) {
                assertTrue(resultSet.next());
                assertEquals("Replacement filters", resultSet.getString(1));
                assertTrue(!resultSet.next());
            }
        }
    }
}
