/**
 * Exercises logical deletion, configured globally through `GlobalConfig.DbConfig` and per field
 * through `@TableLogic`, which turns the injected delete statements into updates and hides
 * deleted rows from the injected select and update statements.
 *
 * A help desk archives tickets through a global `archived` flag and removes ticket notes by
 * stamping a `removed_at` time. It archives tickets by id, by id batch, by column map and by
 * condition, checks that archived tickets disappear from lookups, counts and updates while their
 * rows stay in the table, and removes a note so that only the remaining notes of a ticket are
 * listed while the removed one keeps its body and gains a removal time.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class HelpDeskLogicDeleteTest {

    private JdbcDataSource dataSource;

    private SqlSessionFactory sessionFactory;

    private SqlSession session;

    private TicketMapper tickets;

    private NoteMapper notes;

    @BeforeAll
    void buildSessionFactory() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:help_desk;DB_CLOSE_DELAY=-1");
        Environment environment = new Environment("help-desk", new JdbcTransactionFactory(), dataSource);
        MybatisConfiguration configuration = new MybatisConfiguration(environment);
        GlobalConfig globalConfig = GlobalConfigUtils.defaults();
        globalConfig.setBanner(false);
        globalConfig.getDbConfig()
                .setLogicDeleteField("archived")
                .setLogicDeleteValue("1")
                .setLogicNotDeleteValue("0");
        GlobalConfigUtils.setGlobalConfig(configuration, globalConfig);
        configuration.addMapper(TicketMapper.class);
        configuration.addMapper(NoteMapper.class);
        sessionFactory = new MybatisSqlSessionFactoryBuilder().build(configuration);
    }

    @BeforeEach
    void openEmptyHelpDesk() throws SQLException {
        execute("DROP TABLE IF EXISTS help_ticket");
        execute("DROP TABLE IF EXISTS ticket_note");
        execute("""
                CREATE TABLE help_ticket (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    subject VARCHAR(120) NOT NULL,
                    priority VARCHAR(8) NOT NULL,
                    archived INT DEFAULT 0 NOT NULL
                )
                """);
        execute("""
                CREATE TABLE ticket_note (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ticket_id BIGINT NOT NULL,
                    body VARCHAR(200) NOT NULL,
                    removed_at TIMESTAMP
                )
                """);
        session = sessionFactory.openSession(true);
        tickets = session.getMapper(TicketMapper.class);
        notes = session.getMapper(NoteMapper.class);
    }

    @AfterEach
    void closeSession() {
        session.close();
    }

    @AfterAll
    void shutDownDatabase() throws SQLException {
        execute("SHUTDOWN");
    }

    @Test
    void archivesATicketByIdAndHidesItFromLookupsAndCounts() throws SQLException {
        List<Ticket> opened = openSampleTickets();
        Ticket printer = opened.get(0);
        assertThat(tickets.selectById(printer.getId()).getArchived()).isZero();

        assertThat(tickets.deleteById(printer.getId())).isEqualTo(1);
        assertThat(tickets.deleteById(printer.getId())).isZero();

        assertThat(tickets.selectById(printer.getId())).isNull();
        assertThat(tickets.selectCount(null)).isEqualTo(3L);
        assertThat(tickets.selectList(new QueryWrapper<Ticket>().orderByAsc("id")))
                .extracting(Ticket::getSubject)
                .containsExactly("VPN drops every hour", "Reset my password", "Laptop battery swollen");
        assertThat(tickets.selectBatchIds(List.of(printer.getId(), opened.get(1).getId())))
                .extracting(Ticket::getSubject)
                .containsExactly("VPN drops every hour");

        assertThat(queryLong("SELECT COUNT(*) FROM help_ticket")).isEqualTo(4L);
        assertThat(queryLong("SELECT archived FROM help_ticket WHERE id = " + printer.getId())).isEqualTo(1L);
    }

    @Test
    void archivesTicketsByBatchColumnMapAndCondition() throws SQLException {
        List<Ticket> opened = openSampleTickets();

        assertThat(tickets.deleteBatchIds(List.of(opened.get(0).getId(), opened.get(1).getId())))
                .isEqualTo(2);
        assertThat(tickets.deleteByMap(Map.of("subject", "Reset my password"))).isEqualTo(1);
        assertThat(tickets.delete(new LambdaQueryWrapper<Ticket>().eq(Ticket::getPriority, "HIGH")))
                .isZero();
        assertThat(tickets.delete(new LambdaQueryWrapper<Ticket>().eq(Ticket::getPriority, "MEDIUM")))
                .isEqualTo(1);

        assertThat(tickets.selectCount(null)).isZero();
        assertThat(tickets.exists(new LambdaQueryWrapper<Ticket>().like(Ticket::getSubject, "Laptop")))
                .isFalse();
        assertThat(queryLong("SELECT COUNT(*) FROM help_ticket WHERE archived = 1")).isEqualTo(4L);
    }

    @Test
    void leavesArchivedTicketsUntouchedByUpdates() throws SQLException {
        List<Ticket> opened = openSampleTickets();
        Ticket vpn = opened.get(1);
        assertThat(tickets.deleteById(vpn.getId())).isEqualTo(1);

        Ticket escalate = new Ticket();
        escalate.setId(vpn.getId());
        escalate.setPriority("URGENT");
        assertThat(tickets.updateById(escalate)).isZero();

        int lowered = tickets.update(null, new LambdaUpdateWrapper<Ticket>()
                .set(Ticket::getPriority, "LOW")
                .ne(Ticket::getPriority, "LOW"));
        assertThat(lowered).isEqualTo(1);

        assertThat(tickets.selectList(null))
                .extracting(Ticket::getPriority)
                .containsOnly("LOW");
        assertThat(queryLong("SELECT COUNT(*) FROM help_ticket WHERE priority = 'HIGH' AND archived = 1"))
                .isEqualTo(1L);
    }

    @Test
    void removesANoteByStampingItsRemovalTime() throws SQLException {
        List<Ticket> opened = openSampleTickets();
        Long vpnId = opened.get(1).getId();
        Note restart = Note.of(vpnId, "Asked the user to restart the client");
        Note logs = Note.of(vpnId, "Collected the client logs");
        Note escalated = Note.of(vpnId, "Escalated to the network team");
        for (Note note : List.of(restart, logs, escalated)) {
            assertThat(notes.insert(note)).isEqualTo(1);
        }
        assertThat(notes.insert(Note.of(opened.get(0).getId(), "Replaced the toner"))).isEqualTo(1);

        assertThat(notes.deleteById(logs.getId())).isEqualTo(1);

        assertThat(notes.selectById(logs.getId())).isNull();
        assertThat(notes.selectList(new LambdaQueryWrapper<Note>()
                        .eq(Note::getTicketId, vpnId)
                        .orderByAsc(Note::getId)))
                .extracting(Note::getBody)
                .containsExactly("Asked the user to restart the client", "Escalated to the network team");
        assertThat(notes.selectCount(null)).isEqualTo(3L);

        assertThat(queryLong("SELECT COUNT(*) FROM ticket_note WHERE removed_at IS NOT NULL")).isEqualTo(1L);
        assertThat(queryLong("SELECT COUNT(*) FROM ticket_note WHERE removed_at IS NOT NULL"
                + " AND body = 'Collected the client logs' AND id = " + logs.getId())).isEqualTo(1L);
    }

    /** Opens four live tickets, in id order, that every scenario starts from. */
    private List<Ticket> openSampleTickets() {
        List<Ticket> opened = List.of(
                Ticket.of("Printer jams on page two", "LOW"),
                Ticket.of("VPN drops every hour", "HIGH"),
                Ticket.of("Reset my password", "LOW"),
                Ticket.of("Laptop battery swollen", "MEDIUM"));
        for (Ticket ticket : opened) {
            assertThat(tickets.insert(ticket)).isEqualTo(1);
        }
        return opened;
    }

    private long queryLong(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(sql)) {
            assertThat(resultSet.next()).isTrue();
            return resultSet.getLong(1);
        }
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** The help desk's ticket mapper: its deletes archive through the global logic-delete field. */
    interface TicketMapper extends BaseMapper<Ticket> {
    }

    /** The help desk's note mapper: its deletes stamp the `@TableLogic` removal time. */
    interface NoteMapper extends BaseMapper<Note> {
    }

    /** A help desk ticket; `archived` is the global logic-delete field and needs no annotation. */
    @TableName("help_ticket")
    public static class Ticket {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String subject;

        private String priority;

        private Integer archived;

        static Ticket of(String subject, String priority) {
            Ticket ticket = new Ticket();
            ticket.setSubject(subject);
            ticket.setPriority(priority);
            return ticket;
        }

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getSubject() {
            return subject;
        }

        public void setSubject(String subject) {
            this.subject = subject;
        }

        public String getPriority() {
            return priority;
        }

        public void setPriority(String priority) {
            this.priority = priority;
        }

        public Integer getArchived() {
            return archived;
        }

        public void setArchived(Integer archived) {
            this.archived = archived;
        }
    }

    /** A note on a ticket; a removed note keeps its row and records when it was removed. */
    @TableName("ticket_note")
    public static class Note {

        @TableId(type = IdType.AUTO)
        private Long id;

        private Long ticketId;

        private String body;

        @TableLogic(value = "null", delval = "now()")
        private LocalDateTime removedAt;

        static Note of(Long ticketId, String body) {
            Note note = new Note();
            note.setTicketId(ticketId);
            note.setBody(body);
            return note;
        }

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public Long getTicketId() {
            return ticketId;
        }

        public void setTicketId(Long ticketId) {
            this.ticketId = ticketId;
        }

        public String getBody() {
            return body;
        }

        public void setBody(String body) {
            this.body = body;
        }

        public LocalDateTime getRemovedAt() {
            return removedAt;
        }

        public void setRemovedAt(LocalDateTime removedAt) {
            this.removedAt = removedAt;
        }
    }
}
