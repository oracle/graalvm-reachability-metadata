/**
 * Exercises multi-tenancy through `TenantLineInnerInterceptor` and a `TenantLineHandler`, which
 * rewrites every injected and annotated statement so that it only reads and writes the rows of the
 * tenant the current request runs for.
 *
 * A hosted project tracker serves several companies from one schema. Each request runs for one
 * tenant, whose id the handler reads from a request-scoped holder. New projects are stamped with
 * the tenant, lists and counts show only the tenant's rows, edits and deletions cannot reach
 * another tenant's rows, a joined open-task report is restricted on both joined tables, the shared
 * currency table is exempt from the tenant line, and an operator's statement opts out with
 * `@InterceptorIgnore`.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class ProjectTrackerTenantLineTest {

    private static final long ACME = 1L;

    private static final long GLOBEX = 2L;

    private JdbcDataSource dataSource;

    private SqlSessionFactory sessionFactory;

    @BeforeAll
    void buildSessionFactory() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:project_tracker;DB_CLOSE_DELAY=-1");
        Environment environment = new Environment("tracker", new JdbcTransactionFactory(), dataSource);
        MybatisConfiguration configuration = new MybatisConfiguration(environment);
        GlobalConfig globalConfig = GlobalConfigUtils.defaults();
        globalConfig.setBanner(false);
        GlobalConfigUtils.setGlobalConfig(configuration, globalConfig);
        MybatisPlusInterceptor interceptor = new MybatisPlusInterceptor();
        interceptor.addInnerInterceptor(new TenantLineInnerInterceptor(new RequestTenantHandler()));
        configuration.addInterceptor(interceptor);
        configuration.addMapper(ProjectMapper.class);
        configuration.addMapper(TaskMapper.class);
        configuration.addMapper(CurrencyMapper.class);
        sessionFactory = new MybatisSqlSessionFactoryBuilder().build(configuration);
    }

    @BeforeEach
    void createEmptySchema() throws SQLException {
        execute("DROP TABLE IF EXISTS task");
        execute("DROP TABLE IF EXISTS project");
        execute("DROP TABLE IF EXISTS currency");
        execute("""
                CREATE TABLE project (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tenant_id BIGINT NOT NULL,
                    name VARCHAR(60) NOT NULL,
                    budget_currency CHAR(3) NOT NULL
                )
                """);
        execute("""
                CREATE TABLE task (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tenant_id BIGINT NOT NULL,
                    project_id BIGINT NOT NULL,
                    title VARCHAR(80) NOT NULL,
                    done BOOLEAN NOT NULL
                )
                """);
        execute("""
                CREATE TABLE currency (
                    code CHAR(3) PRIMARY KEY,
                    name VARCHAR(40) NOT NULL
                )
                """);
        execute("INSERT INTO currency (code, name) VALUES ('EUR', 'Euro'), ('USD', 'US Dollar')");
    }

    @AfterAll
    void shutDownDatabase() throws SQLException {
        execute("SHUTDOWN");
    }

    @Test
    void newProjectsAreStampedWithTheRequestTenant() throws SQLException {
        Long rocketId = asTenant(ACME, mappers -> createProject(mappers, "Rocket Skates", "USD"));
        Long magnetId = asTenant(GLOBEX, mappers -> createProject(mappers, "Magnet Ring", "EUR"));

        assertThat(queryLong("SELECT tenant_id FROM project WHERE id = " + rocketId)).isEqualTo(ACME);
        assertThat(queryLong("SELECT tenant_id FROM project WHERE id = " + magnetId)).isEqualTo(GLOBEX);
    }

    @Test
    void listsAndCountsShowOnlyTheTenantsRows() {
        asTenant(ACME, mappers -> {
            createProject(mappers, "Rocket Skates", "USD");
            return createProject(mappers, "Giant Magnet", "USD");
        });
        asTenant(GLOBEX, mappers -> createProject(mappers, "Doomsday Device", "EUR"));

        List<String> acmeProjects = asTenant(ACME, mappers -> mappers.projects()
                .selectList(new LambdaQueryWrapper<Project>().orderByAsc(Project::getName))
                .stream()
                .map(Project::getName)
                .toList());
        assertThat(acmeProjects).containsExactly("Giant Magnet", "Rocket Skates");

        Long acmeCount = asTenant(ACME, mappers -> mappers.projects().selectCount(null));
        Long globexCount = asTenant(GLOBEX, mappers -> mappers.projects().selectCount(null));
        List<Project> foreignLookup = asTenant(GLOBEX, mappers -> mappers.projects().selectList(
                new LambdaQueryWrapper<Project>().eq(Project::getName, "Rocket Skates")));
        assertThat(acmeCount).isEqualTo(2L);
        assertThat(globexCount).isEqualTo(1L);
        assertThat(foreignLookup).isEmpty();
    }

    @Test
    void editsAndDeletionsCannotReachAnotherTenantsRows() throws SQLException {
        Long acmeId = asTenant(ACME, mappers -> createProject(mappers, "Rocket Skates", "USD"));
        asTenant(GLOBEX, mappers -> createProject(mappers, "Rocket Fuel", "EUR"));

        Project hijack = new Project();
        hijack.setId(acmeId);
        hijack.setName("Stolen Skates");
        Integer hijacked = asTenant(GLOBEX, mappers -> mappers.projects().updateById(hijack));
        Project foreignProject = asTenant(GLOBEX, mappers -> mappers.projects().selectById(acmeId));
        assertThat(hijacked).isZero();
        assertThat(foreignProject).isNull();

        Integer rebudgeted = asTenant(ACME, mappers -> mappers.projects().update(null,
                new LambdaUpdateWrapper<Project>()
                        .set(Project::getBudgetCurrency, "EUR")
                        .likeRight(Project::getName, "Rocket")));
        assertThat(rebudgeted).isEqualTo(1);

        Integer deleted = asTenant(GLOBEX, mappers -> mappers.projects().delete(
                new LambdaQueryWrapper<Project>().likeRight(Project::getName, "Rocket")));
        assertThat(deleted).isEqualTo(1);

        Project acmeProject = asTenant(ACME, mappers -> mappers.projects().selectById(acmeId));
        assertThat(acmeProject.getName()).isEqualTo("Rocket Skates");
        assertThat(acmeProject.getBudgetCurrency()).isEqualTo("EUR");
        assertThat(queryLong("SELECT COUNT(*) FROM project")).isEqualTo(1L);
    }

    @Test
    void joinedOpenTaskReportIsRestrictedOnBothTables() {
        asTenant(ACME, mappers -> {
            Long skates = createProject(mappers, "Rocket Skates", "USD");
            Long magnet = createProject(mappers, "Giant Magnet", "USD");
            addTask(mappers, skates, "Attach rockets", false);
            addTask(mappers, skates, "Order wheels", true);
            addTask(mappers, magnet, "Wind the coil", false);
            return skates;
        });
        Long acmeSkates = asTenant(ACME, mappers -> mappers.projects()
                .selectOne(new LambdaQueryWrapper<Project>().eq(Project::getName, "Rocket Skates")).getId());
        asTenant(GLOBEX, mappers -> {
            Long device = createProject(mappers, "Doomsday Device", "EUR");
            addTask(mappers, device, "Hollow out volcano", false);
            addTask(mappers, acmeSkates, "Sabotage skates", false);
            return device;
        });

        List<OpenTask> acmeReport = asTenant(ACME, mappers -> mappers.tasks().openTasks());
        assertThat(acmeReport)
                .extracting(OpenTask::getProjectName, OpenTask::getTitle)
                .containsExactly(
                        tuple("Giant Magnet", "Wind the coil"),
                        tuple("Rocket Skates", "Attach rockets"));

        List<OpenTask> globexReport = asTenant(GLOBEX, mappers -> mappers.tasks().openTasks());
        assertThat(globexReport)
                .extracting(OpenTask::getProjectName, OpenTask::getTitle)
                .containsExactly(tuple("Doomsday Device", "Hollow out volcano"));
    }

    @Test
    void sharedCurrenciesAndOperatorStatementsBypassTheTenantLine() {
        asTenant(ACME, mappers -> createProject(mappers, "Rocket Skates", "USD"));
        asTenant(GLOBEX, mappers -> createProject(mappers, "Doomsday Device", "EUR"));
        asTenant(GLOBEX, mappers -> createProject(mappers, "Magnet Ring", "EUR"));

        List<Currency> currencies = asTenant(ACME, mappers -> mappers.currencies()
                .selectList(new LambdaQueryWrapper<Currency>().orderByAsc(Currency::getCode)));
        assertThat(currencies)
                .extracting(Currency::getCode, Currency::getName)
                .containsExactly(tuple("EUR", "Euro"), tuple("USD", "US Dollar"));

        Long operatorCount = asTenant(ACME, mappers -> mappers.projects().countAcrossTenants());
        Long acmeCount = asTenant(ACME, mappers -> mappers.projects().selectCount(null));
        assertThat(operatorCount).isEqualTo(3L);
        assertThat(acmeCount).isEqualTo(1L);
    }

    /**
     * Serves one request for `tenantId`: binds the tenant to the request, hands the work a session
     * of its own and unbinds the tenant again once the request completes.
     */
    private <T> T asTenant(long tenantId, Function<Mappers, T> work) {
        RequestTenant.bind(tenantId);
        try (SqlSession session = sessionFactory.openSession(true)) {
            return work.apply(new Mappers(
                    session.getMapper(ProjectMapper.class),
                    session.getMapper(TaskMapper.class),
                    session.getMapper(CurrencyMapper.class)));
        } finally {
            RequestTenant.clear();
        }
    }

    private static Long createProject(Mappers mappers, String name, String budgetCurrency) {
        Project project = new Project();
        project.setName(name);
        project.setBudgetCurrency(budgetCurrency);
        assertThat(mappers.projects().insert(project)).isEqualTo(1);
        assertThat(project.getId()).isNotNull();
        return project.getId();
    }

    private static void addTask(Mappers mappers, Long projectId, String title, boolean done) {
        Task task = new Task();
        task.setProjectId(projectId);
        task.setTitle(title);
        task.setDone(done);
        assertThat(mappers.tasks().insert(task)).isEqualTo(1);
    }

    private long queryLong(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(sql)) {
            assertThat(resultSet.next()).isTrue();
            return resultSet.getLong(1);
        }
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** Holds the tenant the current request runs for, as a web filter would bind it. */
    static final class RequestTenant {

        private static final ThreadLocal<Long> CURRENT = new ThreadLocal<>();

        private RequestTenant() {
        }

        static void bind(long tenantId) {
            CURRENT.set(tenantId);
        }

        static long current() {
            Long tenantId = CURRENT.get();
            assertThat(tenantId).as("a statement ran outside of a tenant request").isNotNull();
            return tenantId;
        }

        static void clear() {
            CURRENT.remove();
        }
    }

    /** Supplies the request's tenant to the interceptor and exempts the shared lookup table. */
    static final class RequestTenantHandler implements TenantLineHandler {

        @Override
        public Expression getTenantId() {
            return new LongValue(RequestTenant.current());
        }

        @Override
        public boolean ignoreTable(String tableName) {
            return "currency".equalsIgnoreCase(tableName);
        }
    }

    /** The mappers one request works with, all bound to the request's session. */
    record Mappers(ProjectMapper projects, TaskMapper tasks, CurrencyMapper currencies) {
    }

    /** Projects of the tenant; the operator count deliberately spans all tenants. */
    interface ProjectMapper extends BaseMapper<Project> {

        @InterceptorIgnore(tenantLine = "true")
        @Select("SELECT COUNT(*) FROM project")
        long countAcrossTenants();
    }

    /** Tasks of the tenant, with a report that joins each open task to its project. */
    interface TaskMapper extends BaseMapper<Task> {

        @Select("""
                SELECT p.name AS project_name, t.title
                FROM task t JOIN project p ON p.id = t.project_id
                WHERE t.done = FALSE
                ORDER BY p.name, t.title
                """)
        List<OpenTask> openTasks();
    }

    /** The currencies every tenant shares. */
    interface CurrencyMapper extends BaseMapper<Currency> {
    }

    /** A tenant's project; the tenant column is managed by the interceptor, not the entity. */
    @TableName("project")
    public static class Project {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String name;

        private String budgetCurrency;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getName() {
            return name;
        }

        public void setName(String name) {
            this.name = name;
        }

        public String getBudgetCurrency() {
            return budgetCurrency;
        }

        public void setBudgetCurrency(String budgetCurrency) {
            this.budgetCurrency = budgetCurrency;
        }
    }

    /** A unit of work inside a tenant's project. */
    @TableName("task")
    public static class Task {

        @TableId(type = IdType.AUTO)
        private Long id;

        private Long projectId;

        private String title;

        private Boolean done;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public Long getProjectId() {
            return projectId;
        }

        public void setProjectId(Long projectId) {
            this.projectId = projectId;
        }

        public String getTitle() {
            return title;
        }

        public void setTitle(String title) {
            this.title = title;
        }

        public Boolean getDone() {
            return done;
        }

        public void setDone(Boolean done) {
            this.done = done;
        }
    }

    /** A line of the open-task report. */
    public static class OpenTask {

        private String projectName;

        private String title;

        public String getProjectName() {
            return projectName;
        }

        public void setProjectName(String projectName) {
            this.projectName = projectName;
        }

        public String getTitle() {
            return title;
        }

        public void setTitle(String title) {
            this.title = title;
        }
    }

    /** A currency project budgets are kept in. */
    @TableName("currency")
    public static class Currency {

        @TableId(type = IdType.INPUT)
        private String code;

        private String name;

        public String getCode() {
            return code;
        }

        public void setCode(String code) {
            this.code = code;
        }

        public String getName() {
            return name;
        }

        public void setName(String name) {
            this.name = name;
        }
    }
}
