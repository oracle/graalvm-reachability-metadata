package com_baomidou.mybatis_plus;

import com.baomidou.mybatisplus.annotation.IdType;
import com.baomidou.mybatisplus.annotation.InterceptorIgnore;
import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableLogic;
import com.baomidou.mybatisplus.annotation.TableName;
import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.core.MybatisSqlSessionFactoryBuilder;
import com.baomidou.mybatisplus.core.config.GlobalConfig;
import com.baomidou.mybatisplus.core.conditions.query.LambdaQueryWrapper;
import com.baomidou.mybatisplus.core.conditions.update.LambdaUpdateWrapper;
import com.baomidou.mybatisplus.core.exceptions.MybatisPlusException;
import com.baomidou.mybatisplus.core.mapper.BaseMapper;
import com.baomidou.mybatisplus.core.toolkit.GlobalConfigUtils;
import com.baomidou.mybatisplus.extension.plugins.MybatisPlusInterceptor;
import com.baomidou.mybatisplus.extension.plugins.inner.BlockAttackInnerInterceptor;
import org.apache.ibatis.annotations.Delete;
import org.apache.ibatis.annotations.Param;
import org.apache.ibatis.annotations.Update;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.SqlSession;
import org.apache.ibatis.session.SqlSessionFactory;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Exercises the full-table write guard `BlockAttackInnerInterceptor`, which parses every update
 * and delete before it is prepared and rejects those whose `WHERE` clause is missing or always
 * true, unless the mapper method opts out through `@InterceptorIgnore(blockAttack = "true")`.
 *
 * A newsletter service keeps subscribers and archived campaigns. A careless bulk unsubscribe, a
 * bulk delete with an empty wrapper, and hand-written statements padded with `1 = 1` are stopped
 * before they reach the database, while targeted changes and the yearly purge that is explicitly
 * exempted still go through. Campaigns are logically deleted, so a "delete everything" that only
 * filters on the logic-delete column is stopped as well.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class NewsletterBlockAttackTest {

    private static final String FULL_DELETE = "Prohibition of full table deletion";

    private static final String FULL_UPDATE = "Prohibition of table update operation";

    private JdbcDataSource dataSource;

    private SqlSessionFactory sessionFactory;

    private SqlSession session;

    private SubscriberMapper subscribers;

    private CampaignMapper campaigns;

    @BeforeAll
    void buildSessionFactory() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:newsletter_guard;DB_CLOSE_DELAY=-1");
        Environment environment = new Environment("newsletter", new JdbcTransactionFactory(), dataSource);
        MybatisConfiguration configuration = new MybatisConfiguration(environment);
        GlobalConfig globalConfig = GlobalConfigUtils.defaults();
        globalConfig.setBanner(false);
        GlobalConfigUtils.setGlobalConfig(configuration, globalConfig);
        MybatisPlusInterceptor interceptor = new MybatisPlusInterceptor();
        interceptor.addInnerInterceptor(new BlockAttackInnerInterceptor());
        configuration.addInterceptor(interceptor);
        configuration.addMapper(SubscriberMapper.class);
        configuration.addMapper(CampaignMapper.class);
        sessionFactory = new MybatisSqlSessionFactoryBuilder().build(configuration);
    }

    @BeforeEach
    void openMailingList() throws SQLException {
        execute("DROP TABLE IF EXISTS newsletter_subscriber");
        execute("DROP TABLE IF EXISTS newsletter_campaign");
        execute("""
                CREATE TABLE newsletter_subscriber (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email VARCHAR(80) NOT NULL,
                    status VARCHAR(20) NOT NULL
                )
                """);
        execute("""
                CREATE TABLE newsletter_campaign (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    subject VARCHAR(80) NOT NULL,
                    archived INT NOT NULL DEFAULT 0
                )
                """);
        session = sessionFactory.openSession(true);
        subscribers = session.getMapper(SubscriberMapper.class);
        campaigns = session.getMapper(CampaignMapper.class);
        subscribe("ada@example.org", "ACTIVE");
        subscribe("grace@example.org", "ACTIVE");
        subscribe("linus@example.org", "BOUNCED");
    }

    @AfterEach
    void closeSession() {
        session.close();
    }

    @AfterAll
    void shutDownDatabase() throws SQLException {
        execute("SHUTDOWN");
    }

    @Test
    void bulkUnsubscribeWithoutConditionIsRejected() throws SQLException {
        Subscriber unsubscribed = new Subscriber();
        unsubscribed.setStatus("UNSUBSCRIBED");

        assertThatThrownBy(() -> subscribers.update(unsubscribed, null))
                .hasRootCauseInstanceOf(MybatisPlusException.class)
                .hasStackTraceContaining(FULL_UPDATE);
        assertThatThrownBy(() -> subscribers.update(null, new LambdaUpdateWrapper<Subscriber>()
                .set(Subscriber::getStatus, "UNSUBSCRIBED")))
                .hasRootCauseInstanceOf(MybatisPlusException.class)
                .hasStackTraceContaining(FULL_UPDATE);
        assertThat(queryLong("SELECT COUNT(*) FROM newsletter_subscriber WHERE status = 'UNSUBSCRIBED'"))
                .isZero();

        int updated = subscribers.update(null, new LambdaUpdateWrapper<Subscriber>()
                .set(Subscriber::getStatus, "UNSUBSCRIBED")
                .eq(Subscriber::getStatus, "BOUNCED"));
        assertThat(updated).isEqualTo(1);
        assertThat(subscribers.selectList(new LambdaQueryWrapper<Subscriber>()
                        .eq(Subscriber::getStatus, "UNSUBSCRIBED")))
                .extracting(Subscriber::getEmail)
                .containsExactly("linus@example.org");
    }

    @Test
    void bulkDeleteWithEmptyWrapperIsRejected() throws SQLException {
        assertThatThrownBy(() -> subscribers.delete(new LambdaQueryWrapper<>()))
                .hasRootCauseInstanceOf(MybatisPlusException.class)
                .hasStackTraceContaining(FULL_DELETE);
        assertThatThrownBy(() -> subscribers.delete(null))
                .hasRootCauseInstanceOf(MybatisPlusException.class)
                .hasStackTraceContaining(FULL_DELETE);
        assertThat(queryLong("SELECT COUNT(*) FROM newsletter_subscriber")).isEqualTo(3L);

        assertThat(subscribers.delete(new LambdaQueryWrapper<Subscriber>()
                .eq(Subscriber::getStatus, "BOUNCED"))).isEqualTo(1);
        Subscriber grace = subscribers.selectOne(new LambdaQueryWrapper<Subscriber>()
                .eq(Subscriber::getEmail, "grace@example.org"));
        assertThat(subscribers.deleteById(grace.getId())).isEqualTo(1);
        assertThat(subscribers.selectList(null))
                .extracting(Subscriber::getEmail)
                .containsExactly("ada@example.org");
    }

    @Test
    void handWrittenStatementsWithTautologiesAreRejected() throws SQLException {
        assertThatThrownBy(() -> subscribers.clearAll())
                .hasRootCauseInstanceOf(MybatisPlusException.class)
                .hasStackTraceContaining(FULL_DELETE);
        assertThatThrownBy(() -> subscribers.reactivate("ada@example.org"))
                .hasRootCauseInstanceOf(MybatisPlusException.class)
                .hasStackTraceContaining(FULL_UPDATE);
        assertThat(queryLong("SELECT COUNT(*) FROM newsletter_subscriber WHERE status = 'ACTIVE'"))
                .isEqualTo(2L);

        assertThat(subscribers.markStatus("linus@example.org", "ACTIVE")).isEqualTo(1);
        assertThat(queryLong("SELECT COUNT(*) FROM newsletter_subscriber WHERE status = 'ACTIVE'"))
                .isEqualTo(3L);
    }

    @Test
    void exemptedYearlyPurgeRemovesEverySubscriber() throws SQLException {
        assertThat(subscribers.purgeForNewYear()).isEqualTo(3);
        assertThat(queryLong("SELECT COUNT(*) FROM newsletter_subscriber")).isZero();
        assertThat(subscribers.selectCount(null)).isZero();
    }

    @Test
    void logicalDeleteOfEveryCampaignIsRejected() throws SQLException {
        Long spring = launch("Spring sale");
        launch("Summer sale");

        assertThatThrownBy(() -> campaigns.delete(null))
                .hasRootCauseInstanceOf(MybatisPlusException.class)
                .hasStackTraceContaining(FULL_UPDATE);
        assertThat(queryLong("SELECT COUNT(*) FROM newsletter_campaign WHERE archived = 0")).isEqualTo(2L);

        assertThat(campaigns.deleteById(spring)).isEqualTo(1);
        assertThat(campaigns.selectList(null))
                .extracting(Campaign::getSubject)
                .containsExactly("Summer sale");
        assertThat(queryLong("SELECT archived FROM newsletter_campaign WHERE id = " + spring)).isEqualTo(1L);
    }

    private void subscribe(String email, String status) {
        Subscriber subscriber = new Subscriber();
        subscriber.setEmail(email);
        subscriber.setStatus(status);
        assertThat(subscribers.insert(subscriber)).isEqualTo(1);
    }

    private Long launch(String subject) {
        Campaign campaign = new Campaign();
        campaign.setSubject(subject);
        assertThat(campaigns.insert(campaign)).isEqualTo(1);
        return campaign.getId();
    }

    private long queryLong(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(sql)) {
            assertThat(resultSet.next()).isTrue();
            return resultSet.getLong(1);
        }
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** The subscriber mapper: injected statements plus hand-written maintenance statements. */
    interface SubscriberMapper extends BaseMapper<Subscriber> {

        /** A careless cleanup whose `1 = 1` filter matches every row. */
        @Delete("DELETE FROM newsletter_subscriber WHERE 1 = 1")
        int clearAll();

        /** A reactivation whose `OR 1 = 1` widens it to the whole table. */
        @Update("UPDATE newsletter_subscriber SET status = 'ACTIVE' WHERE email = #{email} OR 1 = 1")
        int reactivate(@Param("email") String email);

        /** A targeted status change for one address. */
        @Update("UPDATE newsletter_subscriber SET status = #{status} WHERE email = #{email}")
        int markStatus(@Param("email") String email, @Param("status") String status);

        /** The yearly purge, deliberately exempted from the full-table guard. */
        @InterceptorIgnore(blockAttack = "true")
        @Delete("DELETE FROM newsletter_subscriber")
        int purgeForNewYear();
    }

    /** The campaign mapper: its deletes are logical updates of the `archived` column. */
    interface CampaignMapper extends BaseMapper<Campaign> {
    }

    /** A mailing-list address and its delivery status. */
    @TableName("newsletter_subscriber")
    public static class Subscriber {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String email;

        private String status;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getEmail() {
            return email;
        }

        public void setEmail(String email) {
            this.email = email;
        }

        public String getStatus() {
            return status;
        }

        public void setStatus(String status) {
            this.status = status;
        }
    }

    /** A sent campaign; deleting it only marks it `archived`. */
    @TableName("newsletter_campaign")
    public static class Campaign {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String subject;

        @TableLogic
        private Integer archived;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getSubject() {
            return subject;
        }

        public void setSubject(String subject) {
            this.subject = subject;
        }

        public Integer getArchived() {
            return archived;
        }

        public void setArchived(Integer archived) {
            this.archived = archived;
        }
    }
}
