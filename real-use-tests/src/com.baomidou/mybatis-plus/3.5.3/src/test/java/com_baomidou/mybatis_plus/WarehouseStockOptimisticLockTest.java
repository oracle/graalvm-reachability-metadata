package com_baomidou.mybatis_plus;

import com.baomidou.mybatisplus.annotation.IdType;
import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableName;
import com.baomidou.mybatisplus.annotation.Version;
import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.core.MybatisSqlSessionFactoryBuilder;
import com.baomidou.mybatisplus.core.config.GlobalConfig;
import com.baomidou.mybatisplus.core.conditions.query.LambdaQueryWrapper;
import com.baomidou.mybatisplus.core.conditions.update.LambdaUpdateWrapper;
import com.baomidou.mybatisplus.core.mapper.BaseMapper;
import com.baomidou.mybatisplus.core.toolkit.GlobalConfigUtils;
import com.baomidou.mybatisplus.extension.plugins.MybatisPlusInterceptor;
import com.baomidou.mybatisplus.extension.plugins.inner.OptimisticLockerInnerInterceptor;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.SqlSession;
import org.apache.ibatis.session.SqlSessionFactory;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.tuple;

/**
 * Exercises optimistic locking through `OptimisticLockerInnerInterceptor` and a `@Version`
 * field, which guards `updateById` and entity-carrying `update` calls with the version the
 * entity was read at and bumps the stored and in-memory version on success.
 *
 * A warehouse keeps stock levels that two clerks read and adjust independently. The first
 * clerk's adjustment wins and advances the version, the second clerk's stale adjustment matches
 * no row until the clerk rereads the item and retries, a conditional restock through an update
 * wrapper honours the version too, and an item without a known version is updated unguarded.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class WarehouseStockOptimisticLockTest {

    private JdbcDataSource dataSource;

    private SqlSessionFactory sessionFactory;

    private SqlSession session;

    private StockItemMapper stock;

    @BeforeAll
    void buildSessionFactory() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:warehouse_stock;DB_CLOSE_DELAY=-1");
        Environment environment = new Environment("warehouse", new JdbcTransactionFactory(), dataSource);
        MybatisConfiguration configuration = new MybatisConfiguration(environment);
        GlobalConfig globalConfig = GlobalConfigUtils.defaults();
        globalConfig.setBanner(false);
        GlobalConfigUtils.setGlobalConfig(configuration, globalConfig);
        MybatisPlusInterceptor interceptor = new MybatisPlusInterceptor();
        interceptor.addInnerInterceptor(new OptimisticLockerInnerInterceptor());
        configuration.addInterceptor(interceptor);
        configuration.addMapper(StockItemMapper.class);
        sessionFactory = new MybatisSqlSessionFactoryBuilder().build(configuration);
    }

    @BeforeEach
    void openEmptyWarehouse() throws SQLException {
        execute("DROP TABLE IF EXISTS stock_item");
        execute("""
                CREATE TABLE stock_item (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sku VARCHAR(20) NOT NULL,
                    quantity INT NOT NULL,
                    version INT NOT NULL
                )
                """);
        session = sessionFactory.openSession(true);
        stock = session.getMapper(StockItemMapper.class);
    }

    @AfterEach
    void closeSession() {
        session.close();
    }

    @AfterAll
    void shutDownDatabase() throws SQLException {
        execute("SHUTDOWN");
    }

    @Test
    void firstAdjustmentWinsAndAdvancesTheVersion() throws SQLException {
        Long boltsId = receive("BOLT-M8", 100);

        StockItem firstClerk = readInOwnSession(boltsId);
        StockItem secondClerk = readInOwnSession(boltsId);
        assertThat(firstClerk.getVersion()).isEqualTo(1);
        assertThat(secondClerk.getVersion()).isEqualTo(1);

        firstClerk.setQuantity(firstClerk.getQuantity() - 30);
        assertThat(stock.updateById(firstClerk)).isEqualTo(1);
        assertThat(firstClerk.getVersion()).isEqualTo(2);

        secondClerk.setQuantity(secondClerk.getQuantity() - 50);
        assertThat(stock.updateById(secondClerk)).isZero();

        StockItem stored = stock.selectById(boltsId);
        assertThat(stored.getQuantity()).isEqualTo(70);
        assertThat(stored.getVersion()).isEqualTo(2);
        assertThat(queryLong("SELECT version FROM stock_item WHERE id = " + boltsId)).isEqualTo(2L);
    }

    @Test
    void staleClerkSucceedsAfterRereadingTheItem() throws SQLException {
        Long nutsId = receive("NUT-M8", 40);
        StockItem stale = readInOwnSession(nutsId);
        StockItem competing = readInOwnSession(nutsId);
        competing.setQuantity(35);
        assertThat(stock.updateById(competing)).isEqualTo(1);

        assertThat(pick(stale, 10)).isZero();

        int attempts = 1;
        int updated = 0;
        while (updated == 0 && attempts < 3) {
            StockItem fresh = readInOwnSession(nutsId);
            updated = pick(fresh, 10);
            attempts++;
        }

        assertThat(updated).isEqualTo(1);
        assertThat(attempts).isEqualTo(2);
        StockItem stored = stock.selectById(nutsId);
        assertThat(stored.getQuantity()).isEqualTo(25);
        assertThat(stored.getVersion()).isEqualTo(3);
        assertThat(queryLong("SELECT quantity FROM stock_item WHERE sku = 'NUT-M8'")).isEqualTo(25L);
    }

    @Test
    void conditionalRestockThroughAWrapperHonoursTheVersion() {
        Long washersId = receive("WASHER-8", 5);
        receive("WASHER-10", 5);
        StockItem lowStock = stock.selectOne(new LambdaQueryWrapper<StockItem>()
                .eq(StockItem::getSku, "WASHER-8"));

        StockItem restock = new StockItem();
        restock.setQuantity(lowStock.getQuantity() + 95);
        restock.setVersion(lowStock.getVersion());
        LambdaUpdateWrapper<StockItem> belowReorderPoint = new LambdaUpdateWrapper<StockItem>()
                .eq(StockItem::getId, washersId)
                .lt(StockItem::getQuantity, 10);
        assertThat(stock.update(restock, belowReorderPoint)).isEqualTo(1);
        assertThat(restock.getVersion()).isEqualTo(2);

        StockItem duplicateRestock = new StockItem();
        duplicateRestock.setQuantity(lowStock.getQuantity() + 95);
        duplicateRestock.setVersion(lowStock.getVersion());
        assertThat(stock.update(duplicateRestock, new LambdaUpdateWrapper<StockItem>()
                .eq(StockItem::getId, washersId))).isZero();

        assertThat(stock.selectList(new LambdaQueryWrapper<StockItem>().orderByAsc(StockItem::getSku)))
                .extracting(StockItem::getSku, StockItem::getQuantity, StockItem::getVersion)
                .containsExactly(
                        tuple("WASHER-10", 5, 1),
                        tuple("WASHER-8", 100, 2));
    }

    @Test
    void updateWithoutAKnownVersionIsNotGuarded() throws SQLException {
        Long screwsId = receive("SCREW-4", 200);
        StockItem audited = stock.selectById(screwsId);
        audited.setQuantity(190);
        assertThat(stock.updateById(audited)).isEqualTo(1);

        StockItem stocktake = new StockItem();
        stocktake.setId(screwsId);
        stocktake.setQuantity(180);
        assertThat(stock.updateById(stocktake)).isEqualTo(1);
        assertThat(stocktake.getVersion()).isNull();

        StockItem stored = stock.selectById(screwsId);
        assertThat(stored.getQuantity()).isEqualTo(180);
        assertThat(stored.getVersion()).isEqualTo(2);
        assertThat(queryLong("SELECT COUNT(*) FROM stock_item")).isEqualTo(1L);
    }

    /** Records a newly received item at version 1 and returns its generated id. */
    private Long receive(String sku, int quantity) {
        StockItem item = new StockItem();
        item.setSku(sku);
        item.setQuantity(quantity);
        item.setVersion(1);
        assertThat(stock.insert(item)).isEqualTo(1);
        assertThat(item.getId()).isNotNull();
        return item.getId();
    }

    /**
     * Reads the item the way a separate clerk would, in a session of its own, so that it gets
     * its own copy instead of the instance cached by the scenario's session.
     */
    private StockItem readInOwnSession(Long id) {
        try (SqlSession clerkSession = sessionFactory.openSession(true)) {
            return clerkSession.getMapper(StockItemMapper.class).selectById(id);
        }
    }

    /** Picks `count` units from the item as read, returning the number of rows the guarded update hit. */
    private int pick(StockItem item, int count) {
        StockItem adjustment = new StockItem();
        adjustment.setId(item.getId());
        adjustment.setVersion(item.getVersion());
        adjustment.setQuantity(item.getQuantity() - count);
        return stock.updateById(adjustment);
    }

    private long queryLong(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(sql)) {
            assertThat(resultSet.next()).isTrue();
            return resultSet.getLong(1);
        }
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** The warehouse's stock mapper: its entity updates are guarded by the `@Version` column. */
    interface StockItemMapper extends BaseMapper<StockItem> {
    }

    /** A stock keeping unit and its on-hand quantity; `version` counts accepted adjustments. */
    @TableName("stock_item")
    public static class StockItem {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String sku;

        private Integer quantity;

        @Version
        private Integer version;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getSku() {
            return sku;
        }

        public void setSku(String sku) {
            this.sku = sku;
        }

        public Integer getQuantity() {
            return quantity;
        }

        public void setQuantity(Integer quantity) {
            this.quantity = quantity;
        }

        public Integer getVersion() {
            return version;
        }

        public void setVersion(Integer version) {
            this.version = version;
        }
    }
}
