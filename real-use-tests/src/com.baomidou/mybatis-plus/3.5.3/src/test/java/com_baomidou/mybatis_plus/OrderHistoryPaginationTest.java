/**
 * Exercises physical pagination through `MybatisPlusInterceptor` with a
 * `PaginationInnerInterceptor` for the H2 dialect.
 *
 * A web shop pages through its order history: it walks the pages of all orders sorted with
 * `OrderItem`s, pages one customer's orders with a lambda wrapper, skips the count query for an
 * infinite-scroll feed, falls back to the first page when a client asks for a page past the end,
 * caps an oversized page at the interceptor's limit, pages map rows from `selectMapsPage`, and
 * pages an annotated join query that declares an `IPage` parameter.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class OrderHistoryPaginationTest {

    private static final String[] CUSTOMERS = {"alice", "bob", "carol"};

    private JdbcDataSource dataSource;

    private SqlSessionFactory sessionFactory;

    @BeforeAll
    void buildSessionFactoryAndStockOrders() throws SQLException {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:order_history;DB_CLOSE_DELAY=-1");
        execute("""
                CREATE TABLE shop_customer (
                    login VARCHAR(32) PRIMARY KEY,
                    country VARCHAR(2) NOT NULL
                )
                """);
        execute("""
                CREATE TABLE shop_order (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    customer VARCHAR(32) NOT NULL,
                    item_count INT NOT NULL,
                    total DECIMAL(10, 2) NOT NULL
                )
                """);
        execute("INSERT INTO shop_customer VALUES ('alice', 'NL'), ('bob', 'RS'), ('carol', 'NL')");

        Environment environment = new Environment("shop", new JdbcTransactionFactory(), dataSource);
        MybatisConfiguration configuration = new MybatisConfiguration(environment);
        PaginationInnerInterceptor pagination = new PaginationInnerInterceptor(DbType.H2);
        pagination.setOverflow(true);
        pagination.setMaxLimit(10L);
        MybatisPlusInterceptor interceptor = new MybatisPlusInterceptor();
        interceptor.addInnerInterceptor(pagination);
        configuration.addInterceptor(interceptor);
        configuration.addMapper(OrderMapper.class);
        sessionFactory = new MybatisSqlSessionFactoryBuilder().build(configuration);

        try (SqlSession session = sessionFactory.openSession(true)) {
            OrderMapper orders = session.getMapper(OrderMapper.class);
            for (int i = 1; i <= 23; i++) {
                ShopOrder order = new ShopOrder();
                order.setCustomer(CUSTOMERS[(i - 1) % CUSTOMERS.length]);
                order.setItemCount(i % 4 + 1);
                order.setTotal(BigDecimal.valueOf(i * 250L, 2));
                assertThat(orders.insert(order)).isEqualTo(1);
            }
        }
    }

    @AfterAll
    void shutDownDatabase() throws SQLException {
        execute("SHUTDOWN");
    }

    @Test
    void walksAllPagesOfTheOrderHistoryNewestFirst() {
        try (SqlSession session = sessionFactory.openSession(true)) {
            OrderMapper orders = session.getMapper(OrderMapper.class);

            Page<ShopOrder> first = orders.selectPage(
                    Page.<ShopOrder>of(1, 5).addOrder(OrderItem.desc("id")), null);
            assertThat(first.getTotal()).isEqualTo(23L);
            assertThat(first.getPages()).isEqualTo(5L);
            assertThat(first.hasPrevious()).isFalse();
            assertThat(first.hasNext()).isTrue();
            assertThat(first.getRecords()).extracting(ShopOrder::getId)
                    .containsExactly(23L, 22L, 21L, 20L, 19L);

            Page<ShopOrder> last = orders.selectPage(
                    Page.<ShopOrder>of(5, 5).addOrder(OrderItem.desc("id")), null);
            assertThat(last.hasNext()).isFalse();
            assertThat(last.hasPrevious()).isTrue();
            assertThat(last.getRecords()).extracting(ShopOrder::getId).containsExactly(3L, 2L, 1L);
        }
    }

    @Test
    void pagesOneCustomersOrdersSortedByItemCountThenTotal() {
        try (SqlSession session = sessionFactory.openSession(true)) {
            OrderMapper orders = session.getMapper(OrderMapper.class);

            Page<ShopOrder> page = orders.selectPage(
                    Page.<ShopOrder>of(2, 3).addOrder(OrderItem.desc("item_count"), OrderItem.asc("total")),
                    new LambdaQueryWrapper<ShopOrder>().eq(ShopOrder::getCustomer, "bob"));

            assertThat(page.getTotal()).isEqualTo(8L);
            assertThat(page.getPages()).isEqualTo(3L);
            assertThat(page.getRecords()).extracting(ShopOrder::getCustomer).containsOnly("bob");
            assertThat(page.getRecords()).extracting(ShopOrder::getId).containsExactly(14L, 5L, 17L);
            assertThat(page.getRecords()).extracting(ShopOrder::getItemCount).containsExactly(3, 2, 2);
        }
    }

    @Test
    void feedsAnInfiniteScrollWithoutCountingOrders() {
        try (SqlSession session = sessionFactory.openSession(true)) {
            OrderMapper orders = session.getMapper(OrderMapper.class);

            Page<ShopOrder> request = new Page<>(3, 4, false);
            request.addOrder(OrderItem.asc("id"));
            Page<ShopOrder> feed = orders.selectPage(request, null);

            assertThat(feed.searchCount()).isFalse();
            assertThat(feed.getTotal()).isZero();
            assertThat(feed.getRecords()).extracting(ShopOrder::getId).containsExactly(9L, 10L, 11L, 12L);
        }
    }

    @Test
    void returnsTheFirstPageForAPagePastTheEndAndCapsOversizedPages() {
        try (SqlSession session = sessionFactory.openSession(true)) {
            OrderMapper orders = session.getMapper(OrderMapper.class);

            Page<ShopOrder> overflow = orders.selectPage(
                    Page.<ShopOrder>of(40, 5).addOrder(OrderItem.asc("id")), null);
            assertThat(overflow.getCurrent()).isEqualTo(1L);
            assertThat(overflow.getRecords()).extracting(ShopOrder::getId)
                    .containsExactly(1L, 2L, 3L, 4L, 5L);

            Page<ShopOrder> oversized = orders.selectPage(
                    Page.<ShopOrder>of(1, 500).addOrder(OrderItem.asc("id")), null);
            assertThat(oversized.getTotal()).isEqualTo(23L);
            assertThat(oversized.getRecords()).hasSize(10);
            assertThat(oversized.getRecords().get(9).getId()).isEqualTo(10L);
        }
    }

    @Test
    void pagesMapRowsAndAnAnnotatedJoinQuery() {
        try (SqlSession session = sessionFactory.openSession(true)) {
            OrderMapper orders = session.getMapper(OrderMapper.class);

            Page<Map<String, Object>> totals = orders.selectMapsPage(
                    Page.<Map<String, Object>>of(1, 2).addOrder(OrderItem.asc("customer")),
                    new LambdaQueryWrapper<ShopOrder>()
                            .select(ShopOrder::getCustomer, ShopOrder::getTotal)
                            .ge(ShopOrder::getTotal, new BigDecimal("50.00")));
            assertThat(totals.getTotal()).isEqualTo(4L);
            assertThat(totals.getRecords()).hasSize(2);
            assertThat(totals.getRecords()).allSatisfy(row -> assertThat(row).containsOnlyKeys("CUSTOMER", "TOTAL"));
            assertThat(totals.getRecords().get(0)).containsEntry("CUSTOMER", "alice");

            IPage<CustomerOrder> dutch = orders.selectOrdersByCountry(
                    Page.<CustomerOrder>of(2, 4).addOrder(OrderItem.desc("o.total")), "NL");
            assertThat(dutch.getTotal()).isEqualTo(15L);
            assertThat(dutch.getPages()).isEqualTo(4L);
            List<CustomerOrder> records = dutch.getRecords();
            assertThat(records).extracting(CustomerOrder::getCountry).containsOnly("NL");
            assertThat(records).extracting(CustomerOrder::getId).containsExactly(16L, 15L, 13L, 12L);
            assertThat(records.get(0).getCustomer()).isEqualTo("alice");
            assertThat(records.get(0).getTotal()).isEqualByComparingTo("40.00");
        }
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** The shop's order mapper: the generic statements plus one annotated paged join. */
    interface OrderMapper extends BaseMapper<ShopOrder> {

        @Select("""
                SELECT o.id, o.customer, o.total, c.country
                FROM shop_order o JOIN shop_customer c ON c.login = o.customer
                WHERE c.country = #{country}
                """)
        IPage<CustomerOrder> selectOrdersByCountry(IPage<CustomerOrder> page, @Param("country") String country);
    }

    /** An order row. */
    @TableName("shop_order")
    public static class ShopOrder {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String customer;

        private Integer itemCount;

        private BigDecimal total;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getCustomer() {
            return customer;
        }

        public void setCustomer(String customer) {
            this.customer = customer;
        }

        public Integer getItemCount() {
            return itemCount;
        }

        public void setItemCount(Integer itemCount) {
            this.itemCount = itemCount;
        }

        public BigDecimal getTotal() {
            return total;
        }

        public void setTotal(BigDecimal total) {
            this.total = total;
        }
    }

    /** One row of the order-by-country report, joined with the customer's country. */
    public static class CustomerOrder {

        private Long id;

        private String customer;

        private BigDecimal total;

        private String country;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getCustomer() {
            return customer;
        }

        public void setCustomer(String customer) {
            this.customer = customer;
        }

        public BigDecimal getTotal() {
            return total;
        }

        public void setTotal(BigDecimal total) {
            this.total = total;
        }

        public String getCountry() {
            return country;
        }

        public void setCountry(String country) {
            this.country = country;
        }
    }
}
