/**
 * Exercises enum column mapping through the `CompositeEnumTypeHandler` that `MybatisConfiguration`
 * installs, which stores `@EnumValue` enums and `IEnum` enums by their declared code and plain
 * enums by name, on injected inserts, selects, updates, wrapper conditions and annotated SQL.
 *
 * A parcel dispatch desk tracks each parcel's status as a numeric code shared with the carriers'
 * systems, its priority as a one-letter code, and its carrier by name. Dispatchers work with the
 * enums only: they insert parcels, filter and bulk-update them by enum, and read rows that a
 * carrier feed wrote straight into the table with raw codes.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class ParcelDispatchEnumMappingTest {

    private JdbcDataSource dataSource;

    private SqlSessionFactory sessionFactory;

    private SqlSession session;

    private ParcelMapper parcels;

    @BeforeAll
    void buildSessionFactory() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:parcel_dispatch;DB_CLOSE_DELAY=-1");
        Environment environment = new Environment("dispatch", new JdbcTransactionFactory(), dataSource);
        MybatisConfiguration configuration = new MybatisConfiguration(environment);
        GlobalConfig globalConfig = GlobalConfigUtils.defaults();
        globalConfig.setBanner(false);
        GlobalConfigUtils.setGlobalConfig(configuration, globalConfig);
        configuration.addMapper(ParcelMapper.class);
        sessionFactory = new MybatisSqlSessionFactoryBuilder().build(configuration);
    }

    @BeforeEach
    void openEmptyDesk() throws SQLException {
        execute("DROP TABLE IF EXISTS parcel");
        execute("""
                CREATE TABLE parcel (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tracking_code VARCHAR(20) NOT NULL,
                    status INT NOT NULL,
                    priority CHAR(1),
                    carrier VARCHAR(20) NOT NULL
                )
                """);
        session = sessionFactory.openSession(true);
        parcels = session.getMapper(ParcelMapper.class);
    }

    @AfterEach
    void closeSession() {
        session.close();
    }

    @AfterAll
    void shutDownDatabase() throws SQLException {
        execute("SHUTDOWN");
    }

    @Test
    void insertStoresDeclaredCodesAndSelectByIdRestoresEnums() throws SQLException {
        Parcel parcel = parcel("TRK-1001", Status.LABEL_PRINTED, Priority.EXPRESS, Carrier.DHL);
        assertThat(parcels.insert(parcel)).isEqualTo(1);
        assertThat(parcel.getId()).isNotNull();

        assertThat(queryRow("SELECT status, priority, carrier FROM parcel WHERE tracking_code = 'TRK-1001'"))
                .containsExactly("10", "E", "DHL");

        Parcel stored = readInOwnSession(parcel.getId());
        assertThat(stored.getStatus()).isSameAs(Status.LABEL_PRINTED);
        assertThat(stored.getPriority()).isSameAs(Priority.EXPRESS);
        assertThat(stored.getCarrier()).isSameAs(Carrier.DHL);
    }

    @Test
    void rowsWrittenByTheCarrierFeedAreReadBackAsEnums() throws SQLException {
        execute("""
                INSERT INTO parcel (tracking_code, status, priority, carrier) VALUES
                    ('FEED-1', 20, 'S', 'UPS'),
                    ('FEED-2', 30, NULL, 'FEDEX')
                """);

        assertThat(parcels.selectList(new LambdaQueryWrapper<Parcel>().orderByAsc(Parcel::getTrackingCode)))
                .extracting(Parcel::getTrackingCode, Parcel::getStatus, Parcel::getPriority, Parcel::getCarrier)
                .containsExactly(
                        tuple("FEED-1", Status.IN_TRANSIT, Priority.STANDARD, Carrier.UPS),
                        tuple("FEED-2", Status.DELIVERED, null, Carrier.FEDEX));
    }

    @Test
    void wrapperConditionsBindEnumsThroughTheirCodes() {
        parcels.insert(parcel("TRK-2001", Status.IN_TRANSIT, Priority.EXPRESS, Carrier.DHL));
        parcels.insert(parcel("TRK-2002", Status.IN_TRANSIT, Priority.STANDARD, Carrier.UPS));
        parcels.insert(parcel("TRK-2003", Status.DELIVERED, Priority.EXPRESS, Carrier.DHL));
        parcels.insert(parcel("TRK-2004", Status.LABEL_PRINTED, Priority.ECONOMY, Carrier.FEDEX));

        List<Parcel> urgentOnTheRoad = parcels.selectList(new LambdaQueryWrapper<Parcel>()
                .eq(Parcel::getStatus, Status.IN_TRANSIT)
                .eq(Parcel::getPriority, Priority.EXPRESS));
        assertThat(urgentOnTheRoad).extracting(Parcel::getTrackingCode).containsExactly("TRK-2001");

        List<Parcel> notYetDelivered = parcels.selectList(new LambdaQueryWrapper<Parcel>()
                .in(Parcel::getStatus, List.of(Status.LABEL_PRINTED, Status.IN_TRANSIT))
                .ne(Parcel::getCarrier, Carrier.UPS)
                .orderByAsc(Parcel::getTrackingCode));
        assertThat(notYetDelivered).extracting(Parcel::getTrackingCode).containsExactly("TRK-2001", "TRK-2004");

        assertThat(parcels.selectCount(new LambdaQueryWrapper<Parcel>().eq(Parcel::getCarrier, Carrier.DHL)))
                .isEqualTo(2L);
    }

    @Test
    void updatesWriteNewCodesForEnumFields() throws SQLException {
        Parcel first = parcel("TRK-3001", Status.IN_TRANSIT, Priority.STANDARD, Carrier.UPS);
        Parcel second = parcel("TRK-3002", Status.IN_TRANSIT, Priority.STANDARD, Carrier.UPS);
        Parcel third = parcel("TRK-3003", Status.LABEL_PRINTED, Priority.ECONOMY, Carrier.DHL);
        parcels.insert(first);
        parcels.insert(second);
        parcels.insert(third);

        Parcel upgraded = readInOwnSession(third.getId());
        upgraded.setPriority(Priority.EXPRESS);
        upgraded.setCarrier(Carrier.FEDEX);
        assertThat(parcels.updateById(upgraded)).isEqualTo(1);

        int delivered = parcels.update(null, new LambdaUpdateWrapper<Parcel>()
                .set(Parcel::getStatus, Status.DELIVERED)
                .eq(Parcel::getStatus, Status.IN_TRANSIT)
                .eq(Parcel::getCarrier, Carrier.UPS));
        assertThat(delivered).isEqualTo(2);

        assertThat(queryRow("SELECT status, priority, carrier FROM parcel WHERE tracking_code = 'TRK-3003'"))
                .containsExactly("10", "E", "FEDEX");
        assertThat(parcels.selectList(new LambdaQueryWrapper<Parcel>().orderByAsc(Parcel::getTrackingCode)))
                .extracting(Parcel::getTrackingCode, Parcel::getStatus, Parcel::getPriority, Parcel::getCarrier)
                .containsExactly(
                        tuple("TRK-3001", Status.DELIVERED, Priority.STANDARD, Carrier.UPS),
                        tuple("TRK-3002", Status.DELIVERED, Priority.STANDARD, Carrier.UPS),
                        tuple("TRK-3003", Status.LABEL_PRINTED, Priority.EXPRESS, Carrier.FEDEX));
    }

    @Test
    void annotatedQueriesBindAndReturnEnums() {
        parcels.insert(parcel("TRK-4001", Status.DELIVERED, Priority.EXPRESS, Carrier.DHL));
        parcels.insert(parcel("TRK-4002", Status.IN_TRANSIT, Priority.ECONOMY, Carrier.DHL));
        parcels.insert(parcel("TRK-4003", Status.DELIVERED, Priority.STANDARD, Carrier.UPS));

        assertThat(parcels.trackingCodesIn(Status.DELIVERED)).containsExactly("TRK-4001", "TRK-4003");
        assertThat(parcels.statusesFor(Carrier.DHL)).containsExactly(Status.DELIVERED, Status.IN_TRANSIT);
        assertThat(parcels.prioritiesFromStatusCode(10)).containsExactly(Priority.ECONOMY, Priority.EXPRESS, Priority.STANDARD);
    }

    private static Parcel parcel(String trackingCode, Status status, Priority priority, Carrier carrier) {
        Parcel parcel = new Parcel();
        parcel.setTrackingCode(trackingCode);
        parcel.setStatus(status);
        parcel.setPriority(priority);
        parcel.setCarrier(carrier);
        return parcel;
    }

    /** Reads the parcel in a session of its own, bypassing the scenario session's local cache. */
    private Parcel readInOwnSession(Long id) {
        try (SqlSession readerSession = sessionFactory.openSession(true)) {
            return readerSession.getMapper(ParcelMapper.class).selectById(id);
        }
    }

    /** Reads the single row the query matches, every column as the string JDBC renders it. */
    private List<String> queryRow(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(sql)) {
            assertThat(resultSet.next()).isTrue();
            List<String> row = new ArrayList<>();
            for (int column = 1; column <= resultSet.getMetaData().getColumnCount(); column++) {
                row.add(resultSet.getString(column));
            }
            assertThat(resultSet.next()).isFalse();
            return row;
        }
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** Delivery progress, stored as the numeric code the carriers' systems exchange. */
    public enum Status {
        LABEL_PRINTED(10, "Label printed"),
        IN_TRANSIT(20, "In transit"),
        DELIVERED(30, "Delivered");

        @EnumValue
        private final int code;

        private final String label;

        Status(int code, String label) {
            this.code = code;
            this.label = label;
        }

        public int getCode() {
            return code;
        }

        public String getLabel() {
            return label;
        }
    }

    /** Handling priority, stored as the one-letter code printed on the parcel label. */
    public enum Priority implements IEnum<String> {
        EXPRESS("E"),
        STANDARD("S"),
        ECONOMY("C");

        private final String letter;

        Priority(String letter) {
            this.letter = letter;
        }

        @Override
        public String getValue() {
            return letter;
        }
    }

    /** The carrier a parcel is handed to, stored by name. */
    public enum Carrier {
        DHL,
        UPS,
        FEDEX
    }

    /** The dispatch desk's parcel mapper, with hand-written queries alongside the injected ones. */
    interface ParcelMapper extends BaseMapper<Parcel> {

        @Select("SELECT tracking_code FROM parcel WHERE status = #{status} ORDER BY tracking_code")
        List<String> trackingCodesIn(@Param("status") Status status);

        @Select("SELECT status FROM parcel WHERE carrier = #{carrier} ORDER BY tracking_code")
        List<Status> statusesFor(@Param("carrier") Carrier carrier);

        @Select("SELECT priority FROM parcel WHERE status >= #{minimumCode} ORDER BY priority")
        List<Priority> prioritiesFromStatusCode(@Param("minimumCode") int minimumCode);
    }

    /** A parcel on the dispatch desk. */
    @TableName("parcel")
    public static class Parcel {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String trackingCode;

        private Status status;

        private Priority priority;

        private Carrier carrier;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getTrackingCode() {
            return trackingCode;
        }

        public void setTrackingCode(String trackingCode) {
            this.trackingCode = trackingCode;
        }

        public Status getStatus() {
            return status;
        }

        public void setStatus(Status status) {
            this.status = status;
        }

        public Priority getPriority() {
            return priority;
        }

        public void setPriority(Priority priority) {
            this.priority = priority;
        }

        public Carrier getCarrier() {
            return carrier;
        }

        public void setCarrier(Carrier carrier) {
            this.carrier = carrier;
        }
    }
}
