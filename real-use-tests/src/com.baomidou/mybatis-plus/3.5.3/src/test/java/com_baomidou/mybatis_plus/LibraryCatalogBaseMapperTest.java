/**
 * Exercises the generic `BaseMapper` CRUD statements that mybatis-plus injects for an annotated
 * entity when a mapper is registered on a `MybatisConfiguration` built by
 * `MybatisSqlSessionFactoryBuilder`.
 *
 * A library catalog keeps its books in an H2 table and declares only an empty `BookMapper`. The
 * catalog shelves new books and reads back their generated ids, looks books up by id, by id
 * batch, by column map and through `QueryWrapper` filters, sorts and aggregates, restocks a book
 * with a partly filled entity whose `null` properties stay untouched, moves old books to the
 * archive with an `UpdateWrapper`, and withdraws books by id, by id batch and by condition.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class LibraryCatalogBaseMapperTest {

    private JdbcDataSource dataSource;

    private SqlSessionFactory sessionFactory;

    private SqlSession session;

    private BookMapper books;

    @BeforeAll
    void buildSessionFactory() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:library_catalog;DB_CLOSE_DELAY=-1");
        Environment environment = new Environment("catalog", new JdbcTransactionFactory(), dataSource);
        MybatisConfiguration configuration = new MybatisConfiguration(environment);
        configuration.addMapper(BookMapper.class);
        sessionFactory = new MybatisSqlSessionFactoryBuilder().build(configuration);
    }

    @BeforeEach
    void openEmptyCatalog() throws SQLException {
        execute("DROP TABLE IF EXISTS catalog_book");
        execute("""
                CREATE TABLE catalog_book (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title VARCHAR(120) NOT NULL,
                    author VARCHAR(80) NOT NULL,
                    published_year INT NOT NULL,
                    copies INT NOT NULL,
                    shelf_code VARCHAR(16) NOT NULL
                )
                """);
        session = sessionFactory.openSession(true);
        books = session.getMapper(BookMapper.class);
    }

    @AfterEach
    void closeSession() {
        session.close();
    }

    @AfterAll
    void shutDownDatabase() throws SQLException {
        execute("SHUTDOWN");
    }

    @Test
    void shelvesBooksAndLooksThemUpByIdBatchAndColumnMap() {
        Book earthsea = Book.of("A Wizard of Earthsea", "Ursula K. Le Guin", 1968, 3, "F-LEG");
        earthsea.setDisplayLabel("never stored");
        Book dispossessed = Book.of("The Dispossessed", "Ursula K. Le Guin", 1974, 2, "F-LEG");
        Book neuromancer = Book.of("Neuromancer", "William Gibson", 1984, 4, "F-GIB");

        assertThat(books.insert(earthsea)).isEqualTo(1);
        assertThat(books.insert(dispossessed)).isEqualTo(1);
        assertThat(books.insert(neuromancer)).isEqualTo(1);

        assertThat(earthsea.getId()).isNotNull();
        assertThat(dispossessed.getId()).isGreaterThan(earthsea.getId());
        assertThat(neuromancer.getId()).isGreaterThan(dispossessed.getId());

        Book found = books.selectById(dispossessed.getId());
        assertThat(found.getTitle()).isEqualTo("The Dispossessed");
        assertThat(found.getAuthor()).isEqualTo("Ursula K. Le Guin");
        assertThat(found.getPublishedYear()).isEqualTo(1974);
        assertThat(found.getCopies()).isEqualTo(2);
        assertThat(found.getShelf()).isEqualTo("F-LEG");
        assertThat(found.getDisplayLabel()).isNull();

        assertThat(books.selectById(neuromancer.getId() + 100)).isNull();

        assertThat(books.selectBatchIds(List.of(earthsea.getId(), neuromancer.getId())))
                .extracting(Book::getTitle)
                .containsExactlyInAnyOrder("A Wizard of Earthsea", "Neuromancer");

        assertThat(books.selectByMap(Map.of("author", "Ursula K. Le Guin", "shelf_code", "F-LEG")))
                .extracting(Book::getTitle)
                .containsExactlyInAnyOrder("A Wizard of Earthsea", "The Dispossessed");
    }

    @Test
    void searchesTheCatalogWithQueryWrapperFiltersSortsAndAggregates() {
        shelveSampleCollection();

        List<Book> lateLeGuin = books.selectList(new QueryWrapper<Book>()
                .eq("author", "Ursula K. Le Guin")
                .ge("published_year", 1970)
                .orderByAsc("published_year"));
        assertThat(lateLeGuin)
                .extracting(Book::getTitle)
                .containsExactly("The Dispossessed", "The Telling");

        assertThat(books.selectCount(new QueryWrapper<Book>().like("title", "The"))).isEqualTo(2L);
        assertThat(books.exists(new QueryWrapper<Book>().eq("shelf_code", "F-GIB"))).isTrue();
        assertThat(books.exists(new QueryWrapper<Book>().eq("shelf_code", "F-ASI"))).isFalse();

        Book cyberpunk = books.selectOne(new QueryWrapper<Book>()
                .eq("author", "William Gibson")
                .lt("published_year", 1990));
        assertThat(cyberpunk.getTitle()).isEqualTo("Neuromancer");

        List<Book> scarce = books.selectList(new QueryWrapper<Book>()
                .select("id", "title")
                .between("copies", 1, 2)
                .or(wrapper -> wrapper.isNull("title").or().eq("published_year", 1968))
                .orderByDesc("title"));
        assertThat(scarce)
                .extracting(Book::getTitle)
                .containsExactly("The Telling", "The Dispossessed", "A Wizard of Earthsea");
        assertThat(scarce).extracting(Book::getAuthor).containsOnlyNulls();

        List<Map<String, Object>> copiesPerAuthor = books.selectMaps(new QueryWrapper<Book>()
                .select("author", "SUM(copies) AS total_copies")
                .groupBy("author")
                .having("SUM(copies) > {0}", 3)
                .orderByAsc("author"));
        assertThat(copiesPerAuthor).hasSize(2);
        assertThat(copiesPerAuthor.get(0))
                .containsEntry("AUTHOR", "Ursula K. Le Guin")
                .containsEntry("TOTAL_COPIES", 6L);
        assertThat(copiesPerAuthor.get(1))
                .containsEntry("AUTHOR", "William Gibson")
                .containsEntry("TOTAL_COPIES", 9L);

        List<Object> mostStocked = books.selectObjs(new QueryWrapper<Book>()
                .select("title")
                .orderByDesc("copies")
                .last("FETCH FIRST 2 ROWS ONLY"));
        assertThat(mostStocked).containsExactly("Neuromancer", "Pattern Recognition");
    }

    @Test
    void restocksWithPartialEntitiesAndArchivesWithUpdateWrappers() {
        List<Book> collection = shelveSampleCollection();
        Book earthsea = collection.get(0);

        Book restock = new Book();
        restock.setId(earthsea.getId());
        restock.setCopies(7);
        assertThat(books.updateById(restock)).isEqualTo(1);

        Book restocked = books.selectById(earthsea.getId());
        assertThat(restocked.getCopies()).isEqualTo(7);
        assertThat(restocked.getTitle()).isEqualTo("A Wizard of Earthsea");
        assertThat(restocked.getShelf()).isEqualTo("F-LEG");

        int archived = books.update(null, new UpdateWrapper<Book>()
                .set("shelf_code", "ARCHIVE")
                .setSql("copies = copies - 1")
                .lt("published_year", 1980));
        assertThat(archived).isEqualTo(2);

        Book relabel = new Book();
        relabel.setShelf("F-CYB");
        int relabelled = books.update(relabel, new UpdateWrapper<Book>().eq("author", "William Gibson"));
        assertThat(relabelled).isEqualTo(2);

        assertThat(books.selectList(new QueryWrapper<Book>().orderByAsc("id")))
                .extracting(Book::getShelf, Book::getCopies)
                .containsExactly(
                        tuple("ARCHIVE", 6),
                        tuple("ARCHIVE", 1),
                        tuple("F-CYB", 5),
                        tuple("F-LEG", 1),
                        tuple("F-CYB", 4));
    }

    @Test
    void withdrawsBooksByIdBatchColumnMapAndCondition() {
        List<Book> collection = shelveSampleCollection();

        assertThat(books.deleteById(collection.get(0).getId())).isEqualTo(1);
        assertThat(books.deleteById(collection.get(0).getId())).isZero();
        assertThat(books.deleteBatchIds(List.of(collection.get(1).getId(), collection.get(2).getId())))
                .isEqualTo(2);
        assertThat(books.deleteByMap(Map.of("title", "The Telling"))).isEqualTo(1);
        assertThat(books.delete(new QueryWrapper<Book>().eq("author", "Isaac Asimov"))).isZero();

        assertThat(books.selectCount(null)).isEqualTo(1L);
        assertThat(books.selectList(null))
                .extracting(Book::getTitle)
                .containsExactly("Pattern Recognition");

        assertThat(books.delete(new QueryWrapper<Book>().gt("copies", 0))).isEqualTo(1);
        assertThat(books.selectCount(null)).isZero();
    }

    /** Shelves five books, in id order, that the search and update scenarios share. */
    private List<Book> shelveSampleCollection() {
        List<Book> collection = List.of(
                Book.of("A Wizard of Earthsea", "Ursula K. Le Guin", 1968, 3, "F-LEG"),
                Book.of("The Dispossessed", "Ursula K. Le Guin", 1974, 2, "F-LEG"),
                Book.of("Neuromancer", "William Gibson", 1984, 5, "F-GIB"),
                Book.of("The Telling", "Ursula K. Le Guin", 2000, 1, "F-LEG"),
                Book.of("Pattern Recognition", "William Gibson", 2003, 4, "F-GIB"));
        for (Book book : collection) {
            assertThat(books.insert(book)).isEqualTo(1);
        }
        return collection;
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** The catalog's mapper: every statement it runs is injected by mybatis-plus. */
    interface BookMapper extends BaseMapper<Book> {
    }

    /** A catalog row; the shelf is mapped explicitly and the display label is never stored. */
    @TableName("catalog_book")
    public static class Book {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String title;

        private String author;

        private Integer publishedYear;

        private Integer copies;

        @TableField("shelf_code")
        private String shelf;

        @TableField(exist = false)
        private String displayLabel;

        static Book of(String title, String author, int publishedYear, int copies, String shelf) {
            Book book = new Book();
            book.setTitle(title);
            book.setAuthor(author);
            book.setPublishedYear(publishedYear);
            book.setCopies(copies);
            book.setShelf(shelf);
            return book;
        }

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getTitle() {
            return title;
        }

        public void setTitle(String title) {
            this.title = title;
        }

        public String getAuthor() {
            return author;
        }

        public void setAuthor(String author) {
            this.author = author;
        }

        public Integer getPublishedYear() {
            return publishedYear;
        }

        public void setPublishedYear(Integer publishedYear) {
            this.publishedYear = publishedYear;
        }

        public Integer getCopies() {
            return copies;
        }

        public void setCopies(Integer copies) {
            this.copies = copies;
        }

        public String getShelf() {
            return shelf;
        }

        public void setShelf(String shelf) {
            this.shelf = shelf;
        }

        public String getDisplayLabel() {
            return displayLabel;
        }

        public void setDisplayLabel(String displayLabel) {
            this.displayLabel = displayLabel;
        }
    }
}
