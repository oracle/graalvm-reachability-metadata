import static org.assertj.core.api.Assertions.tuple;

/**
 * Exercises automatic field filling through a `MetaObjectHandler` registered on `GlobalConfig`
 * and `@TableField(fill = ...)` columns, which stamps audit columns on injected inserts,
 * `updateById` and entity-carrying `update(entity, wrapper)` calls.
 *
 * A contract registry records who created and last modified each contract and when. Clerks
 * never set those columns themselves: the handler stamps creation columns on insert, keeps a
 * creation date an import already carries, stamps modification columns on every entity update,
 * and leaves the creation columns untouched by later updates.
 */
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class ContractRegistryAuditFillTest {

    private static final LocalDateTime OPENING = LocalDateTime.of(2024, 3, 1, 9, 0);

    private final AuditContext audit = new AuditContext();

    private JdbcDataSource dataSource;

    private SqlSessionFactory sessionFactory;

    private SqlSession session;

    private ContractMapper contracts;

    @BeforeAll
    void buildSessionFactory() {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:contract_registry;DB_CLOSE_DELAY=-1");
        Environment environment = new Environment("registry", new JdbcTransactionFactory(), dataSource);
        MybatisConfiguration configuration = new MybatisConfiguration(environment);
        GlobalConfig globalConfig = GlobalConfigUtils.defaults();
        globalConfig.setBanner(false);
        globalConfig.setMetaObjectHandler(new AuditFillHandler(audit));
        GlobalConfigUtils.setGlobalConfig(configuration, globalConfig);
        configuration.addMapper(ContractMapper.class);
        sessionFactory = new MybatisSqlSessionFactoryBuilder().build(configuration);
    }

    @BeforeEach
    void openEmptyRegistry() throws SQLException {
        execute("DROP TABLE IF EXISTS contract");
        execute("""
                CREATE TABLE contract (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    reference VARCHAR(20) NOT NULL,
                    status VARCHAR(20) NOT NULL,
                    created_by VARCHAR(40) NOT NULL,
                    created_at TIMESTAMP NOT NULL,
                    modified_by VARCHAR(40),
                    modified_at TIMESTAMP
                )
                """);
        audit.signIn("alice", OPENING);
        session = sessionFactory.openSession(true);
        contracts = session.getMapper(ContractMapper.class);
    }

    @AfterEach
    void closeSession() {
        session.close();
    }

    @AfterAll
    void shutDownDatabase() throws SQLException {
        execute("SHUTDOWN");
    }

    @Test
    void insertStampsCreationColumnsAndLeavesModificationEmpty() throws SQLException {
        Contract lease = draft("LEASE-001");
        assertThat(contracts.insert(lease)).isEqualTo(1);

        assertThat(lease.getCreatedBy()).isEqualTo("alice");
        assertThat(lease.getCreatedAt()).isEqualTo(OPENING);
        assertThat(lease.getModifiedBy()).isNull();
        assertThat(lease.getModifiedAt()).isNull();

        Contract stored = readInOwnSession(lease.getId());
        assertThat(stored.getCreatedBy()).isEqualTo("alice");
        assertThat(stored.getCreatedAt()).isEqualTo(OPENING);
        assertThat(stored.getModifiedBy()).isNull();
        assertThat(queryString("SELECT created_by FROM contract WHERE reference = 'LEASE-001'"))
                .isEqualTo("alice");
        assertThat(queryTimestamp("SELECT created_at FROM contract WHERE reference = 'LEASE-001'"))
                .isEqualTo(OPENING);
    }

    @Test
    void importedContractKeepsItsOriginalCreationDate() {
        LocalDateTime signedOnPaper = LocalDateTime.of(2019, 11, 4, 14, 30);
        Contract legacy = draft("LEGACY-042");
        legacy.setCreatedAt(signedOnPaper);
        assertThat(contracts.insert(legacy)).isEqualTo(1);

        Contract stored = readInOwnSession(legacy.getId());
        assertThat(stored.getCreatedAt()).isEqualTo(signedOnPaper);
        assertThat(stored.getCreatedBy()).isEqualTo("alice");
    }

    @Test
    void updateByIdStampsModificationAndKeepsCreation() throws SQLException {
        Contract supply = draft("SUPPLY-007");
        contracts.insert(supply);

        LocalDateTime approval = OPENING.plusDays(2);
        audit.signIn("bob", approval);
        Contract approved = readInOwnSession(supply.getId());
        approved.setStatus("APPROVED");
        assertThat(contracts.updateById(approved)).isEqualTo(1);
        assertThat(approved.getModifiedBy()).isEqualTo("bob");
        assertThat(approved.getModifiedAt()).isEqualTo(approval);

        LocalDateTime renewal = OPENING.plusDays(30);
        audit.signIn("carol", renewal);
        Contract renewed = readInOwnSession(supply.getId());
        renewed.setStatus("RENEWED");
        assertThat(contracts.updateById(renewed)).isEqualTo(1);

        Contract stored = readInOwnSession(supply.getId());
        assertThat(stored.getStatus()).isEqualTo("RENEWED");
        assertThat(stored.getCreatedBy()).isEqualTo("alice");
        assertThat(stored.getCreatedAt()).isEqualTo(OPENING);
        assertThat(stored.getModifiedBy()).isEqualTo("carol");
        assertThat(stored.getModifiedAt()).isEqualTo(renewal);
        assertThat(queryTimestamp("SELECT modified_at FROM contract WHERE reference = 'SUPPLY-007'"))
                .isEqualTo(renewal);
    }

    @Test
    void bulkStatusChangeThroughAWrapperStampsEveryMatchedRow() {
        contracts.insert(draft("NDA-100"));
        contracts.insert(draft("NDA-101"));
        contracts.insert(draft("LEASE-200"));

        LocalDateTime expiry = OPENING.plusYears(1);
        audit.signIn("system", expiry);
        Contract expired = new Contract();
        expired.setStatus("EXPIRED");
        int updated = contracts.update(expired, new LambdaUpdateWrapper<Contract>()
                .likeRight(Contract::getReference, "NDA-"));
        assertThat(updated).isEqualTo(2);

        assertThat(contracts.selectList(new LambdaQueryWrapper<Contract>().orderByAsc(Contract::getReference)))
                .extracting(Contract::getReference, Contract::getStatus, Contract::getCreatedBy,
                        Contract::getModifiedBy, Contract::getModifiedAt)
                .containsExactly(
                        tuple("LEASE-200", "DRAFT", "alice", null, null),
                        tuple("NDA-100", "EXPIRED", "alice", "system", expiry),
                        tuple("NDA-101", "EXPIRED", "alice", "system", expiry));
    }

    /** A new contract as a clerk drafts it: no audit columns set. */
    private static Contract draft(String reference) {
        Contract contract = new Contract();
        contract.setReference(reference);
        contract.setStatus("DRAFT");
        return contract;
    }

    /** Reads the contract in a session of its own, bypassing the scenario session's local cache. */
    private Contract readInOwnSession(Long id) {
        try (SqlSession readerSession = sessionFactory.openSession(true)) {
            return readerSession.getMapper(ContractMapper.class).selectById(id);
        }
    }

    private String queryString(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(sql)) {
            assertThat(resultSet.next()).isTrue();
            return resultSet.getString(1);
        }
    }

    private LocalDateTime queryTimestamp(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection();
                Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(sql)) {
            assertThat(resultSet.next()).isTrue();
            Timestamp timestamp = resultSet.getTimestamp(1);
            return timestamp.toLocalDateTime();
        }
    }

    private void execute(String sql) throws SQLException {
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    /** Who is signed in to the registry and the time its clock reads, as the handler sees them. */
    static final class AuditContext {

        private String operator;

        private LocalDateTime now;

        void signIn(String operator, LocalDateTime now) {
            this.operator = operator;
            this.now = now;
        }

        String operator() {
            return operator;
        }

        LocalDateTime now() {
            return now;
        }
    }

    /**
     * Stamps audit columns from the signed-in operator and the registry clock. Creation columns
     * are filled strictly, so a value the entity already carries wins; modification columns are
     * always overwritten, since an entity read back from the table already holds the old stamp.
     */
    static final class AuditFillHandler implements MetaObjectHandler {

        private final AuditContext audit;

        AuditFillHandler(AuditContext audit) {
            this.audit = audit;
        }

        @Override
        public void insertFill(MetaObject metaObject) {
            strictInsertFill(metaObject, "createdBy", String.class, audit.operator());
            strictInsertFill(metaObject, "createdAt", LocalDateTime.class, audit.now());
        }

        @Override
        public void updateFill(MetaObject metaObject) {
            setFieldValByName("modifiedBy", audit.operator(), metaObject);
            setFieldValByName("modifiedAt", audit.now(), metaObject);
        }
    }

    /** The registry's contract mapper; audit columns are filled by the handler, never by callers. */
    interface ContractMapper extends BaseMapper<Contract> {
    }

    /** A registered contract and its audit trail. */
    @TableName("contract")
    public static class Contract {

        @TableId(type = IdType.AUTO)
        private Long id;

        private String reference;

        private String status;

        @TableField(fill = FieldFill.INSERT)
        private String createdBy;

        @TableField(fill = FieldFill.INSERT)
        private LocalDateTime createdAt;

        @TableField(fill = FieldFill.UPDATE)
        private String modifiedBy;

        @TableField(fill = FieldFill.UPDATE)
        private LocalDateTime modifiedAt;

        public Long getId() {
            return id;
        }

        public void setId(Long id) {
            this.id = id;
        }

        public String getReference() {
            return reference;
        }

        public void setReference(String reference) {
            this.reference = reference;
        }

        public String getStatus() {
            return status;
        }

        public void setStatus(String status) {
            this.status = status;
        }

        public String getCreatedBy() {
            return createdBy;
        }

        public void setCreatedBy(String createdBy) {
            this.createdBy = createdBy;
        }

        public LocalDateTime getCreatedAt() {
            return createdAt;
        }

        public void setCreatedAt(LocalDateTime createdAt) {
            this.createdAt = createdAt;
        }

        public String getModifiedBy() {
            return modifiedBy;
        }

        public void setModifiedBy(String modifiedBy) {
            this.modifiedBy = modifiedBy;
        }

        public LocalDateTime getModifiedAt() {
            return modifiedAt;
        }

        public void setModifiedAt(LocalDateTime modifiedAt) {
            this.modifiedAt = modifiedAt;
        }
    }
}
