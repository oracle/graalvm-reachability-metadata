"""The setup verdict as a skip record (§FS-unsupportable-version-diagnosis.3).

A recorded skip goes from `setup-check` straight to `publish` with an index-only
tree, a skip edit on any other label is reverted, and a verdict the index
rejects falls through to the normal setup and repair.
"""
from __future__ import annotations

import json
import os
import subprocess
import unittest
from typing import Any

from support import FakeRepository, working_directory
from test_prepare import prepare_arguments
from test_workflow import URLS

import forge_run  # noqa: E402
from exit_codes import OK, SKIP_RECORDED  # noqa: E402
from run_state import RunState, load, read_json, runtime_path  # noqa: E402

REASON: str = "Defines classes from generated bytecode at runtime, which a native image cannot load."
PUBLISHER_SKIP_TEMPLATES: frozenset[str] = frozenset({
    "library-update-request", "fixes-javac-fail", "fixes-java-run-fail", "fixes-native-image-run-fail"})


class SkipRecordTest(unittest.TestCase):

    def setUp(self) -> None:
        self.fake: FakeRepository = FakeRepository()
        self.addCleanup(self.fake.close)
        self.fake.supported_library()

    def step(self, *argv: str) -> int:
        with working_directory(self.fake.workspace):
            return forge_run.main(list(argv))

    @property
    def state(self) -> RunState:
        return load(self.fake.workspace)

    def index(self) -> list[dict[str, Any]]:
        state: RunState = self.state
        with open(state.path(state.index_path), encoding="utf-8") as handle:
            return json.load(handle)

    def gradle_calls(self) -> str:
        with open(os.path.join(self.state.worktree, "gradle-calls.log"), encoding="utf-8") as handle:
            return handle.read()

    def prepare(self, label: str) -> None:
        self.fake.issue(label)
        self.assertEqual(OK, self.step(*prepare_arguments()))

    def setup_verdict(self) -> None:
        """Play `setup` with an unsupportable verdict for 2.0.0, plus the URLs."""
        state: RunState = self.state
        entries: list[dict[str, Any]] = self.index()
        for entry in entries:
            entry.update(URLS)
        entries[0]["skipped-versions"] = [{"version": "2.0.0", "reason": REASON}]
        with open(state.path(state.index_path), "w", encoding="utf-8") as handle:
            json.dump(entries, handle, indent=2)

    def repaired(self) -> None:
        """The setup tail falls through, and `jvm` and `native-repair` run the version."""
        self.assertEqual(OK, self.step("setup-check"))
        self.assertEqual(OK, self.step("jvm"))
        self.assertEqual(OK, self.step("native-repair"))

    def test_run_note_names_the_bar_only_on_fails_labels(self) -> None:
        self.prepare("fails-java-run")
        with open(runtime_path(self.fake.workspace, "run.md"), encoding="utf-8") as handle:
            self.assertIn("SOLE PATH", handle.read())

    def test_recorded_skip_routes_to_publish_with_an_index_only_tree(self) -> None:
        self.prepare("fails-javac-compile")
        self.setup_verdict()

        self.assertEqual(SKIP_RECORDED, self.step("setup-check"))
        state: RunState = self.state
        self.assertTrue(state.skip_recorded)
        self.assertTrue(state.index_only)
        self.assertIsNone(state.not_for_native_image)
        self.assertNotIn("javaTest", self.gradle_calls())
        self.assertIn("validateIndexFiles -Pcoordinates=org.example:lib:2.0.0", self.gradle_calls())
        self.assertFalse(os.path.exists(state.path(state.test_dir)))
        entry: dict[str, Any] = self.index()[-1]
        self.assertEqual(["1.5.0"], entry["tested-versions"])
        self.assertEqual([{"version": "2.0.0", "reason": REASON}], entry["skipped-versions"])
        self.assertIsNone(forge_run.outcome("setup-check", SKIP_RECORDED))

        self.assertEqual(OK, self.step("publish"))
        state = self.state
        self.assertEqual("completed", read_json(runtime_path(self.fake.workspace, forge_run.OUTCOME))["outcome"])
        changed: list[str] = subprocess.run(
            ["git", "diff", "--name-only", state.base_commit, "HEAD"], cwd=state.worktree, check=True,
            stdout=subprocess.PIPE, text=True).stdout.split()
        self.assertEqual(["metadata/org.example/lib/index.json", "stats/org.example/lib/2.0.0/forge-publication.json"],
                         changed)
        descriptor: dict[str, Any] = read_json(state.path("stats/org.example/lib/2.0.0/forge-publication.json"))
        self.assertIn(descriptor["template_type"], PUBLISHER_SKIP_TEMPLATES)
        self.assertEqual(("fixes-javac-fail", "success"),
                         (descriptor["task_type"], descriptor["local_ci_verification"]["status"]))
        self.assertTrue(descriptor["modifiers"]["chunk_final"])
        self.assertIsNone(descriptor["render"]["library_stats"])

    def test_skip_edit_on_another_label_is_reverted(self) -> None:
        self.prepare("library-update-request")
        self.setup_verdict()

        self.repaired()
        entry: dict[str, Any] = self.index()[0]
        self.assertNotIn("skipped-versions", entry)
        self.assertEqual(URLS["source-code-url"], entry["source-code-url"])
        self.assertFalse(self.state.skip_recorded)
        self.assertIn("javaTest", self.gradle_calls())

    def test_rejected_index_falls_through_to_repair(self) -> None:
        self.prepare("fails-java-run")
        self.setup_verdict()
        self.fake.control({"indexFails": True})

        self.repaired()
        state: RunState = self.state
        self.assertFalse(state.skip_recorded)
        self.assertTrue(os.path.isdir(state.path(state.test_dir)))
        entry: dict[str, Any] = self.index()[0]
        self.assertNotIn("skipped-versions", entry)
        self.assertIn("2.0.0", entry["tested-versions"])
        self.assertEqual(URLS["source-code-url"], entry["source-code-url"])
        self.assertIn("javaTest", self.gradle_calls())
        log: str = subprocess.run(["git", "log", "--format=%s", f"{state.base_commit}..HEAD"], cwd=state.worktree,
                                  check=True, stdout=subprocess.PIPE, text=True).stdout
        self.assertNotIn("Record skipped versions", log)

    def test_a_version_already_recorded_falls_through_to_repair(self) -> None:
        with open(os.path.join(self.fake.repo, "metadata/org.example/lib/index.json"), encoding="utf-8") as handle:
            base: dict[str, Any] = json.load(handle)[0]
        base["skipped-versions"] = [{"version": "2.0.0", "reason": REASON}]
        self.fake.write("metadata/org.example/lib/index.json", json.dumps([base], indent=2))
        self.fake.commit("record 2.0.0 as skipped")
        self.prepare("fails-javac-compile")
        state: RunState = self.state
        entries: list[dict[str, Any]] = self.index()
        recorded: dict[str, Any] = next(entry for entry in entries if "skipped-versions" in entry)
        recorded["skipped-versions"].append({"version": "2.0.1", "reason": REASON})
        with open(state.path(state.index_path), "w", encoding="utf-8") as handle:
            json.dump(entries, handle, indent=2)

        self.repaired()
        self.assertFalse(self.state.skip_recorded)
        recorded = next(entry for entry in self.index() if "skipped-versions" in entry)
        self.assertEqual(["2.0.0"], [record["version"] for record in recorded["skipped-versions"]])
        self.assertIn("javaTest", self.gradle_calls())


if __name__ == "__main__":
    unittest.main()
